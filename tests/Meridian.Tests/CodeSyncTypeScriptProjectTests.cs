using Meridian.Core.CodeSync;
using Meridian.Serialization.CodeSync;

namespace Meridian.Tests;

/// <summary>
/// TypeScript module resolution through project files: tsconfig / jsconfig (extends chains, baseUrl, paths, rootDirs,
/// ${configDir}) and monorepo workspaces (package.json workspaces, pnpm-workspace.yaml, exports / types / main), on
/// realistic Nx and Turborepo + pnpm layouts. Packages outside the snapshot stay external.
/// </summary>
public class CodeSyncTypeScriptProjectTests
{
    private static CodeModel Read(params (string Path, string Content)[] files) =>
        new TypeScriptCodeReader().Read(files.Select(f => new CodeFile(f.Path, f.Content)).ToList());

    private static CodeType Type(CodeModel m, string symbol) => Assert.Single(m.Types, t => t.Symbol == symbol);
    private static CodeMember Member(CodeType t, string name) => Assert.Single(t.Members, x => x.Name == name);

    // ================================================================ Nx: tsconfig.base.json paths

    private static readonly (string, string)[] Nx =
    [
        ("nx.json", """{ "npmScope": "station" }"""),
        ("package.json", """{ "name": "station", "private": true, "devDependencies": { "nx": "19.0.0" } }"""),
        ("tsconfig.base.json", """
            {
              // Generated by Nx; comments and trailing commas are allowed.
              "compileOnSave": false,
              "compilerOptions": {
                "rootDir": ".",
                "baseUrl": ".",
                "paths": {
                  "@station/power": ["libs/power/src/index.ts"],
                  "@station/power/*": ["libs/power/src/lib/*"],
                  "@station/*": ["libs/*/src/index.ts"],
                },
              },
              "exclude": ["node_modules", "tmp"]
            }
            """),
        ("apps/ground/tsconfig.json", """
            {
              "extends": "../../tsconfig.base.json",
              "files": [],
              "include": [],
              "references": [{ "path": "./tsconfig.app.json" }]
            }
            """),
        ("apps/ground/tsconfig.app.json", """{ "extends": "./tsconfig.json", "compilerOptions": { "outDir": "../../dist/out-tsc" } }"""),
        ("apps/ground/src/app/console.ts", """
            import { Battery, cells, Charger as NamedCharger } from '@station/power';
            import Charger from '@station/power';
            import type { Telemetry } from '@station/telemetry';
            import { Cell } from '@station/power/cell';
            import { Logger } from 'pino';

            export class Console {
              battery: Battery;
              cell: Cell;
              pack: cells.Pack;
              telemetry: Telemetry;
              charger: Charger;
              named: NamedCharger;
              logger: Logger;
              inline: import("@station/power").Battery;
              external: import("pino").Logger;
            }
            """),
        ("libs/power/src/index.ts", """
            export * from './lib/battery';
            export * as cells from './lib/cell';
            export { default as Charger } from './lib/charger';
            export { default } from './lib/charger';
            """),
        ("libs/power/src/lib/battery.ts", "export class Battery {}"),
        ("libs/power/src/lib/cell.ts", "export class Cell {}\nexport class Pack {}"),
        ("libs/power/src/lib/charger.ts", "export default class Charger {}"),
        ("libs/telemetry/src/index.ts", "export interface Telemetry { at: number }"),
    ];

    [Fact]
    public void Nx_path_aliases_resolve_through_the_base_config_with_the_longest_pattern_winning()
    {
        var m = Read(Nx);
        Assert.Empty(m.Warnings);
        var console = Type(m, "apps.ground.src.app.Console");

        Assert.Equal("libs.power.src.lib.Battery", Member(console, "battery").TypeSymbol);
        Assert.Equal("libs.power.src.lib.Cell", Member(console, "cell").TypeSymbol);          // "@station/power/*" beats "@station/*"
        Assert.Equal("libs.power.src.lib.Pack", Member(console, "pack").TypeSymbol);          // export * as cells
        Assert.Equal("libs.telemetry.src.Telemetry", Member(console, "telemetry").TypeSymbol); // import type, "@station/*"
        Assert.Equal("libs.power.src.lib.Charger", Member(console, "charger").TypeSymbol);    // export { default } from
        Assert.Equal("libs.power.src.lib.Charger", Member(console, "named").TypeSymbol);      // export { default as Charger } from
        Assert.Equal("libs.power.src.lib.Battery", Member(console, "inline").TypeSymbol);
        Assert.Equal("Battery", Member(console, "inline").TypeName);
    }

    [Fact]
    public void External_packages_make_no_dependency_and_keep_a_clean_name()
    {
        var console = Type(Read(Nx), "apps.ground.src.app.Console");
        var logger = Member(console, "logger");
        Assert.Null(logger.TypeSymbol);
        Assert.Equal("Logger", logger.TypeName);
        var inline = Member(console, "external");
        Assert.Null(inline.TypeSymbol);
        Assert.Equal("Logger", inline.TypeName);
        Assert.DoesNotContain(console.Dependencies, d => d.Contains("Logger", StringComparison.Ordinal));
        Assert.DoesNotContain(console.DependencyLocations, u => u.Symbol.Contains("Logger", StringComparison.Ordinal));
    }

    [Fact]
    public void Imports_through_aliases_are_recorded_as_dependency_locations()
    {
        var console = Type(Read(Nx), "apps.ground.src.app.Console");
        Assert.Equal(["apps/ground/src/app/console.ts:1 import", "apps/ground/src/app/console.ts:8 field", "apps/ground/src/app/console.ts:15 field"],
            console.LocationsOf("libs.power.src.lib.Battery").Select(u => $"{u.Location} {u.KindName}"));
    }

    // ================================================================ Turborepo + pnpm workspaces

    private static readonly (string, string)[] Turbo =
    [
        ("package.json", """{ "name": "acme", "private": true, "scripts": { "build": "turbo run build" }, "packageManager": "pnpm@9.0.0" }"""),
        ("pnpm-workspace.yaml", """
            # Workspace packages
            packages:
              - "apps/*"
              - 'packages/*'
              - "!packages/legacy"
            catalog:
              react: ^18.3.1
            """),
        ("turbo.json", """{ "tasks": { "build": { "dependsOn": ["^build"] } } }"""),
        ("packages/tsconfig/package.json", """{ "name": "@acme/tsconfig", "private": true, "files": ["base.json", "nextjs.json"] }"""),
        ("packages/tsconfig/base.json", """{ "compilerOptions": { "strict": true, "moduleResolution": "Bundler" } }"""),
        ("packages/tsconfig/nextjs.json", """
            {
              "extends": "./base.json",
              "compilerOptions": { "baseUrl": "${configDir}", "paths": { "~/*": ["./src/*"] } }
            }
            """),
        ("apps/web/package.json", """{ "name": "web", "dependencies": { "@acme/ui": "workspace:*", "@acme/utils": "workspace:*", "react": "catalog:" } }"""),
        ("apps/web/tsconfig.json", """{ "extends": "@acme/tsconfig/nextjs.json", "include": ["src", "next-env.d.ts"] }"""),
        ("apps/web/src/pages/dashboard.ts", """
            import { Button } from "@acme/ui";
            import { Gauge } from "@acme/ui/gauge";
            import { Store } from "~/state/store";
            import { Units } from "@acme/utils";
            import type { ReactNode } from "react";

            export class Dashboard {
              button: Button;
              gauge: Gauge;
              store: Store;
              units: Units;
              child: ReactNode;
            }
            """),
        ("apps/web/src/state/store.ts", "export class Store {}"),
        ("packages/ui/package.json", """
            {
              "name": "@acme/ui",
              "exports": {
                ".": { "types": "./dist/index.d.ts", "import": "./dist/index.mjs", "require": "./dist/index.js" },
                "./*": { "types": "./dist/components/*.d.ts", "default": "./dist/components/*.js" }
              }
            }
            """),
        ("packages/ui/src/index.ts", "export * from \"./components/button\";"),
        ("packages/ui/src/components/button.ts", "export class Button {}"),
        ("packages/ui/src/components/gauge.ts", "import { Button } from \"./button\";\nexport class Gauge extends Button {}"),
        ("packages/utils/package.json", """{ "name": "@acme/utils", "main": "./dist/index.js", "types": "./dist/index.d.ts" }"""),
        ("packages/utils/src/index.ts", "export class Units {}"),
        // Excluded by "!packages/legacy" although it claims the same name.
        ("packages/legacy/package.json", """{ "name": "@acme/ui", "main": "src/index.ts" }"""),
        ("packages/legacy/src/index.ts", "export class Button {}"),
        ("node_modules/react/package.json", """{ "name": "react" }"""),
    ];

    [Fact]
    public void Turborepo_workspace_packages_resolve_to_their_source_through_exports_types_and_main()
    {
        var m = Read(Turbo);
        Assert.Empty(m.Warnings);
        var dash = Type(m, "apps.web.src.pages.Dashboard");

        Assert.Equal("packages.ui.src.components.Button", Member(dash, "button").TypeSymbol);   // exports "." types → dist → src
        Assert.Equal("packages.ui.src.components.Gauge", Member(dash, "gauge").TypeSymbol);     // exports "./*"
        Assert.Equal("apps.web.src.state.Store", Member(dash, "store").TypeSymbol);             // paths from an extended package config, ${configDir}
        Assert.Equal("packages.utils.src.Units", Member(dash, "units").TypeSymbol);             // types / main → src
        Assert.Null(Member(dash, "child").TypeSymbol);                                          // react: external
        Assert.Equal("ReactNode", Member(dash, "child").TypeName);
        Assert.DoesNotContain(m.Types, t => t.Symbol.StartsWith("node_modules", StringComparison.Ordinal));
    }

    [Fact]
    public void Npm_and_yarn_workspaces_in_package_json_are_read_too()
    {
        var m = Read(
            ("package.json", """{ "private": true, "workspaces": { "packages": ["packages/**"] } }"""),
            ("packages/core/power/package.json", """{ "name": "@sat/power", "exports": "./src/index.ts" }"""),
            ("packages/core/power/src/index.ts", "export { Battery as default, Battery } from './battery';"),
            ("packages/core/power/src/battery.ts", "export class Battery {}"),
            ("packages/app/src/main.ts", "import Battery from '@sat/power';\nimport { Battery as B } from '@sat/power';\nexport class Main { a: Battery; b: B; }"));
        var main = Type(m, "packages.app.src.Main");
        Assert.Equal("packages.core.power.src.Battery", Member(main, "a").TypeSymbol);
        Assert.Equal("packages.core.power.src.Battery", Member(main, "b").TypeSymbol);
    }

    [Fact]
    public void Root_dirs_merge_folders_for_relative_imports()
    {
        var m = Read(
            ("tsconfig.json", """{ "compilerOptions": { "rootDirs": ["src", "generated"] } }"""),
            ("generated/views/model.ts", "export class Model {}"),
            ("src/views/view.ts", "import { Model } from './model';\nexport class View { model: Model }"));
        Assert.Equal("generated.views.Model", Member(Type(m, "src.views.View"), "model").TypeSymbol);
    }

    [Fact]
    public void A_jsconfig_is_used_when_there_is_no_tsconfig_and_the_nearest_config_wins()
    {
        var m = Read(
            ("jsconfig.json", """{ "compilerOptions": { "baseUrl": "lib" } }"""),
            ("lib/clock.ts", "export class Clock {}"),
            ("app/main.ts", "import { Clock } from 'clock';\nexport class Main { c: Clock }"),
            ("tools/tsconfig.json", """{ "compilerOptions": { "baseUrl": "." } }"""),
            ("tools/clock.ts", "export class Clock {}"),
            ("tools/run.ts", "import { Clock } from 'clock';\nexport class Run { c: Clock }"));
        Assert.Equal("lib.Clock", Member(Type(m, "app.Main"), "c").TypeSymbol);
        Assert.Equal("tools.Clock", Member(Type(m, "tools.Run"), "c").TypeSymbol);
    }

    [Fact]
    public void Paths_without_baseUrl_are_relative_to_the_config_that_declares_them_and_extends_may_be_a_list()
    {
        var m = Read(
            ("configs/tsconfig.paths.json", """{ "compilerOptions": { "paths": { "#domain/*": ["../domain/*"] } } }"""),
            ("configs/tsconfig.strict.json", """{ "compilerOptions": { "strict": true } }"""),
            ("tsconfig.json", """{ "extends": ["./configs/tsconfig.paths", "./configs/tsconfig.strict.json"] }"""),
            ("domain/rover.ts", "export class Rover {}"),
            ("app/garage.ts", "import { Rover } from '#domain/rover';\nexport class Garage { rover: Rover }"));
        Assert.Equal("domain.Rover", Member(Type(m, "app.Garage"), "rover").TypeSymbol);
    }

    [Fact]
    public void Bad_or_cyclic_configuration_never_fails_the_read()
    {
        var m = Read(
            ("tsconfig.json", """{ "extends": "./b.json", "compilerOptions": { "paths": { "@/*": ["src/*"] } } }"""),
            ("b.json", """{ "extends": "./tsconfig.json" }"""),
            ("tsconfig.b.json", """{ "extends": "./tsconfig.json" }"""),
            ("packages/x/tsconfig.json", """{ "extends": "./tsconfig.json" """),
            ("packages/x/a.ts", "import { Y } from '@/y';\nexport class A { y: Y }"),
            ("src/y.ts", "export class Y {}"),
            ("src/z.ts", "import { Y } from '@/y';\nexport class Z { y: Y }"));
        Assert.Equal("src.Y", Member(Type(m, "src.Z"), "y").TypeSymbol);
        // The broken config is reported and ignored: "@/" still falls back to src/.
        Assert.Contains(m.Warnings, w => w.StartsWith("packages/x/tsconfig.json:", StringComparison.Ordinal) && w.Contains("invalid JSON", StringComparison.Ordinal));
        Assert.Equal("src.Y", Member(Type(m, "packages.x.A"), "y").TypeSymbol);
    }

    [Fact]
    public void Project_files_are_read_but_never_from_node_modules()
    {
        var r = new TypeScriptCodeReader();
        Assert.True(r.Handles("tsconfig.json"));
        Assert.True(r.Handles("apps/web/tsconfig.app.json"));
        Assert.True(r.Handles("jsconfig.json"));
        Assert.True(r.Handles("packages/ui/package.json"));
        Assert.True(r.Handles("pnpm-workspace.yaml"));
        Assert.True(r.Handles("packages/typescript-config/base.json"));   // a shared config package
        Assert.False(r.Handles("node_modules/react/package.json"));
        Assert.False(r.Handles("tsconfig.yaml"));
        Assert.False(r.Handles("data/settings.json"));
        // Project files alone are not code.
        Assert.Empty(Read(("package.json", "{}"), ("tsconfig.json", "{}")).Types);
    }
}
