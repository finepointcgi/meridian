using System.Text;
using Meridian.Core.Analysis;
using Meridian.Core.Language;
using Meridian.Core.Model;

namespace Meridian.Assistant.Engine;

/// <summary>The stable system prompt (cached), the per-turn model context and the quick-action prompts.</summary>
public static class Prompts
{
    /// <summary>Never changes between requests, so it and the tool list form a cacheable prefix.</summary>
    public const string System = """
        You are the modeling assistant inside Meridian, an MBSE tool for SysML v1/UML models (blocks, parts, ports, requirements,
        test cases, activities, state machines, use cases, packages and diagrams). You help systems engineers understand, review
        and extend the model that is open in their workbench.

        How you work:
        - Every user message starts with a <context> block: the project summary, the active diagram and the current selection.
          Use it to resolve "this", "here" and "the selected block". It is generated by Meridian, not typed by the user.
        - Look things up with the read tools (search_elements, get_element, list_diagrams, get_traceability, validate_model,
          get_sysml_text, plan_diagrams) instead of guessing. Element ids look like _3f2a9c…; never invent ids.
        - The write tools (create_element, update_fields, create_relationship, delete_element, create_diagram_with_elements,
          create_diagrams, apply_sysml_text) only PROPOSE changes. Meridian collects them into one change set that the user reviews as a diff and
          applies (as a single undo step) or discards. Never say a change has been made; say it is proposed and ready to review.
        - Elements you propose return a reference such as new:3; use it as the owner, a relationship end or diagram content in
          later calls of the same turn.
        - If a tool returns an error, read it, fix the input and try again (or explain the problem); do not repeat the same call.
        - Some users are view-only. They can ask anything; they just cannot apply proposals, so only propose changes when asked.

        Modeling conventions:
        - Requirement fields: reqId, text (one atomic, testable "shall" statement with units and tolerances), rationale,
          verifyMethod (test, analysis, inspection or demonstration), priority (low, medium, high, critical), status.
        - Satisfy: design element → requirement. Verify: test case → requirement. DeriveReqt: derived requirement → source
          requirement. Refine: refining element → requirement. Allocate: behavior → structure. Composition: whole → part type.
        - Avoid vague wording (adequate, user-friendly, fast, as appropriate, TBD, etc.) and quantities without units.

        How to answer:
        - Use concise GitHub-flavored Markdown: short paragraphs, bullet lists, tables when comparing items.
        - Mention model elements as links in the form [Element name](el:ELEMENT_ID) so the user can click through to them.
          Only use ids you saw in tool results or the context block. For proposed elements, write their name in bold instead.
        - Be precise and brief. Prefer acting through tools over explaining what you would do.
        """;

    /// <summary>The automatically included workbench context (selection, active diagram, project summary).</summary>
    public static string Context(ModelRepository m, string projectName, Element? selection, Diagram? active, bool readOnly)
    {
        var sb = new StringBuilder();
        sb.AppendLine("<context>");
        var elements = m.AllElements.Count(e => e is not Relationship && e is not Diagram) - 1;
        sb.AppendLine($"Project: {projectName} (model root \"{m.Root.Name}\", id {m.Root.Id}): {elements} elements, " +
                      $"{m.Relationships.Count()} relationships, {m.Diagrams.Count()} diagrams. User access: {(readOnly ? "view-only" : "can edit")}.");
        var counts = m.AllElements.Where(e => e is not Relationship && e is not Diagram && e.Kind != ElementKind.Model)
                      .GroupBy(e => e.Kind).OrderByDescending(g => g.Count()).Take(10).Select(g => $"{g.Count()} {g.Key}");
        sb.AppendLine("Contents: " + string.Join(", ", counts));
        var coverage = Traceability.Coverage(m);
        if (coverage.Total > 0)
            sb.AppendLine($"Requirement coverage: {coverage.Satisfied}/{coverage.Total} satisfied, {coverage.Verified}/{coverage.Total} verified.");
        sb.AppendLine("Top-level packages: " + string.Join(", ", m.Root.OwnedElements.Where(e => e.Kind == ElementKind.Package).Take(20)
                                                     .Select(p => $"{p.Name} (id {p.Id}, {p.Descendants().Count(d => d is not Relationship)} elements)")));
        if (active != null)
        {
            var shown = active.Nodes.Select(n => n.Element).Distinct().ToList();
            sb.AppendLine($"Active diagram: \"{active.Name}\" ({Metamodel.DisplayName(active.DiagramType)}, id {active.Id}, owned by {active.Owner?.QualifiedName}) showing {shown.Count} elements: " +
                          string.Join(", ", shown.Take(40).Select(e => $"{e.DisplayName} [{e.Kind}, {e.Id}]")) + (shown.Count > 40 ? ", …" : ""));
        }
        else sb.AppendLine("Active diagram: none.");
        if (selection != null)
        {
            sb.Append($"Selection: {Metamodel.DisplayName(selection.Kind)} \"{selection.DisplayName}\" (id {selection.Id}), {selection.QualifiedName}");
            if (selection.Kind == ElementKind.Requirement)
                sb.Append($"; {selection.Get(FieldKeys.RequirementId)}: {Truncate(selection.Get(FieldKeys.Text), 400)}");
            sb.AppendLine(".");
        }
        else sb.AppendLine("Selection: nothing selected.");
        sb.Append("</context>");
        return sb.ToString();
    }

    private static string Truncate(string s, int max) => s.Length <= max ? s : s[..max] + "…";

    private static string Scope(Element? scope) =>
        scope is null || scope.Kind == ElementKind.Model ? "the whole model" : $"package \"{scope.Name}\" (id {scope.Id}) and everything inside it";

    public static string GenerateRequirements(ModelRepository m, Element package, string specification)
    {
        var next = m.NextRequirementId();
        return $"""
            Generate requirements from the specification below and propose them in package "{package.Name}" (id {package.Id}).
            For each requirement call create_element (kind Requirement, owner_id {package.Id}) with a short name and fields:
            reqId (the next free id is {next}; number the rest consecutively in the same format), text (one atomic, verifiable
            "shall" statement with units), rationale (why, traced to the specification), verifyMethod (test, analysis, inspection
            or demonstration). Group closely related requirements; propose DeriveReqt links where one clearly derives from another.
            Check for existing similar requirements first (search_elements) and do not duplicate them.
            Finish with a table: id, name, verification method. Mention anything ambiguous in the specification.

            <specification>
            {specification}
            </specification>
            """;
    }

    public static string SuggestTraceLinks(Element? scope) => $"""
        Suggest missing trace links in {Scope(scope)}. Find requirements without satisfy or verify links
        (search_elements with "kind:Requirement where no:satisfy" and "no:verify", scoped with in: when a package is given),
        inspect candidate blocks, parts, activities and test cases, and propose Satisfy, Verify and DeriveReqt links with
        create_relationship. Give every link a confidence between 0 and 1 and a one-sentence reason. Only propose links you
        can justify (confidence at least 0.4); quality over quantity, at most 25. Finish with a short table of the proposals
        (requirement, link, element, confidence) and list requirements for which you found no plausible candidate.
        """;

    public static string ReviewModel(Element? scope) => $"""
        Review {Scope(scope)} for gaps. Check: requirements that are not satisfied or not verified; orphan blocks (not typing
        any part, not satisfying or allocated anything, not on any diagram); vague "shall" wording (adequate, appropriate,
        user-friendly, fast, flexible, TBD, etc.) and non-atomic requirements; numeric values or value properties without
        units; missing rationale or verification method. Use validate_model, search_elements and get_element.
        Then call report_findings ONCE with every finding (severity, category, message, element_id), most important first,
        and end with a brief summary of the model's overall health. Do not propose model changes in this review.
        """;

    public static readonly string[] DiagramKinds = ["Block definition diagram", "Internal block diagram", "Activity diagram", "Package diagram"];

    /// <summary>"Diagram my model": Claude chooses the views that tell the story; Meridian's auto-diagrammer lays them out.</summary>
    public static string DiagramModel(Element? scope) => $"""
        Diagram {Scope(scope)}: choose the set of diagrams that best explains it to a new engineer, and propose them.
        1. Call plan_diagrams{(scope is null or { Kind: ElementKind.Model } ? "" : $" with scope_id {scope.Id}")} to see the candidate views (Meridian's
           deterministic plan) and list_diagrams to see what already exists. Look at key elements with get_element when it helps.
        2. Decide which views tell the story: usually a package overview first, then the main structure (BDD), the internal structure of
           the important blocks (IBD), the key behaviors, and requirement views. Skip views that would only repeat an existing diagram,
           merge or split candidates where that reads better, and leave out clutter (exclude_ids) such as helper or unused elements.
        3. Call create_diagrams ONCE with every diagram you chose: a short readable name (e.g. "Drone – internal structure"), the owner,
           a one-line purpose, and element_ids (or omit them for the owner's default content). Keep each diagram under about 25 shapes.
        Meridian lays every diagram out automatically. Finish with a short table: diagram, type, purpose.
        """;

    public static string DiagramFromDescription(Element owner, string diagramKind, string description)
    {
        var how = diagramKind switch
        {
            "Internal block diagram" => "Create a context block (unless a suitable one exists), part properties typed by blocks, ports and connectors between ports; then create_diagram_with_elements with diagram_type InternalBlock owned by the context block, showing the parts.",
            "Package diagram" => "Create packages (nested inside each other where that helps) and Dependency relationships from each package to the packages it uses; then create_diagram_with_elements with diagram_type Package owned by the target package, showing every package (nested packages are drawn inside their owner, dependencies as arrows).",
            "Activity diagram" => "Create an Activity, then inside it an InitialNode, Actions, Decision/Fork nodes as needed and an ActivityFinalNode, linked with ControlFlow relationships in order; then create_diagram_with_elements with diagram_type Activity owned by the Activity, showing every node.",
            _ => "Create blocks (and value types where useful), Composition relationships from wholes to part types and Generalizations where they apply; then create_diagram_with_elements with diagram_type BlockDefinition owned by the package, showing the blocks.",
        };
        return $"""
            Model the system described below and propose a {diagramKind} for it, owned by "{owner.Name}" (id {owner.Id}).
            {how}
            Reuse existing elements when they match (search first). Keep it to what the description supports.
            Finish with a short summary of the proposed structure.

            <description>
            {description}
            </description>
            """;
    }
}
