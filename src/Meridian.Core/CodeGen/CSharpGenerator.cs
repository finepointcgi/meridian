using System.Text;
using Meridian.Core.Language;
using Meridian.Core.Model;

namespace Meridian.Core.CodeGen;

/// <summary>Forward engineering: generates C# source skeletons from structural classifiers.</summary>
public static class CSharpGenerator
{
    public static IReadOnlyDictionary<string, string> Generate(ModelRepository model)
    {
        var files = new Dictionary<string, string>();
        foreach (var c in model.AllElements.Where(e => Metamodel.IsStructuralClassifier(e.Kind) && e.Kind != ElementKind.Actor))
        {
            var ns = Namespace(c);
            var path = Path.Combine(ns.Split('.').Append(Identifier(c.Name) + ".cs").ToArray());
            if (files.ContainsKey(path)) path = path[..^3] + "_" + c.Id[^6..] + ".cs";
            files[path] = GenerateFile(model, c);
        }
        return files;
    }

    public static string GenerateFile(ModelRepository model, Element c)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>Generated by Meridian from the model. Changes may be overwritten.</auto-generated>");
        sb.AppendLine($"namespace {Namespace(c)};");
        sb.AppendLine();
        Doc(sb, c.Documentation, "");

        var vis = Visibility(c, "public");
        var name = Identifier(c.Name);
        if (c.Kind == ElementKind.Enumeration)
        {
            sb.AppendLine($"{vis} enum {name}");
            sb.AppendLine("{");
            foreach (var lit in c.OwnedElements.Where(x => x.Kind == ElementKind.EnumerationLiteral))
                sb.AppendLine($"    {Identifier(lit.Name)},");
            sb.AppendLine("}");
            return sb.ToString();
        }

        var isInterface = c.Kind is ElementKind.Interface or ElementKind.InterfaceBlock;
        var keyword = isInterface ? "interface" : c.Kind is ElementKind.DataType or ElementKind.ValueType ? "record" : "class";
        var bases = model.General(c).Select(g => Identifier(g.Name))
            .Concat(model.Outgoing(c, ElementKind.Realization).Select(r => Identifier(r.Target.Name))).ToList();
        var abs = c.IsAbstract && !isInterface ? "abstract " : "";
        sb.AppendLine($"{vis} {abs}{keyword} {(isInterface ? "I" + name.TrimStart('I') : name)}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : "")}");
        sb.AppendLine("{");

        foreach (var p in c.OwnedElements.Where(x => x.Kind is ElementKind.Property or ElementKind.Port))
        {
            Doc(sb, p.Documentation, "    ");
            var type = MapType(model, p);
            var def = string.IsNullOrEmpty(p.Get(FieldKeys.DefaultValue)) ? "" : $" = {p.Get(FieldKeys.DefaultValue)};";
            if (IsMany(p.Multiplicity)) { type = $"List<{type}>"; if (def == "" && !isInterface) def = " = new();"; }
            else if (p.Multiplicity.StartsWith('0')) type += "?";
            var pv = isInterface ? "" : Visibility(p, "public") + " ";
            sb.AppendLine($"    {pv}{type} {Pascal(p.Name)} {{ get; set; }}{def}");
        }

        // Navigable association / composition ends become properties too.
        foreach (var r in model.Outgoing(c).Where(r => r.Kind is ElementKind.Association or ElementKind.Composition or ElementKind.Aggregation))
        {
            var t = Identifier(r.Target.Name);
            var propName = string.IsNullOrEmpty(r.Name) ? Pascal(r.Target.Name) : Pascal(r.Name);
            if (IsMany(r.Multiplicity)) sb.AppendLine($"    public List<{t}> {propName}s {{ get; set; }} = new();");
            else sb.AppendLine($"    public {t}{(r.Multiplicity.StartsWith('0') ? "?" : "")} {propName} {{ get; set; }}{(isInterface ? "" : " = default!;")}");
        }

        foreach (var o in c.OwnedElements.Where(x => x.Kind == ElementKind.Operation))
        {
            Doc(sb, o.Documentation, "    ");
            var (pars, ret) = ParseSignature(o.Get(FieldKeys.Signature));
            var ov = isInterface ? "" : Visibility(o, "public") + " ";
            var body = isInterface ? ";" : " => throw new NotImplementedException();";
            sb.AppendLine($"    {ov}{ret} {Pascal(o.Name)}({pars}){body}");
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static bool IsMany(string m) => m.Contains('*') || (m.Contains("..") && m.Split("..")[1].Trim() != "1");

    private static void Doc(StringBuilder sb, string doc, string indent)
    {
        if (string.IsNullOrWhiteSpace(doc)) return;
        sb.AppendLine($"{indent}/// <summary>");
        foreach (var line in doc.Split('\n')) sb.AppendLine($"{indent}/// {line.TrimEnd()}");
        sb.AppendLine($"{indent}/// </summary>");
    }

    private static string Visibility(Element e, string fallback) =>
        e.Get(FieldKeys.Visibility) switch { "private" => "private", "protected" => "protected", "package" => "internal", "public" => "public", _ => fallback };

    public static string Namespace(Element e)
    {
        var parts = e.AncestorsAndSelf().Skip(1).Reverse().Where(a => a.Kind is ElementKind.Model or ElementKind.Package).Select(a => Identifier(a.Name)).ToList();
        return parts.Count == 0 ? "Model" : string.Join(".", parts);
    }

    private static string MapType(ModelRepository model, Element p)
    {
        var t = model.ResolveType(p);
        if (t != null) return Identifier(t.Name);
        return p.TypeRef switch
        {
            "" => "object",
            "Boolean" => "bool",
            "Integer" => "int",
            "Real" => "double",
            "String" => "string",
            "UnlimitedNatural" => "long",
            var other => Identifier(other),
        };
    }

    /// <summary>Parses "(a : Integer, b : String) : Boolean" into C# parameter list and return type.</summary>
    public static (string Parameters, string Return) ParseSignature(string sig)
    {
        if (string.IsNullOrWhiteSpace(sig)) return ("", "void");
        var close = sig.LastIndexOf(')');
        var open = sig.IndexOf('(');
        var ret = "void";
        var pars = "";
        if (open >= 0 && close > open)
        {
            pars = string.Join(", ", sig[(open + 1)..close].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                .Select(p => p.Split(':', 2, StringSplitOptions.TrimEntries))
                .Select(p => p.Length == 2 ? $"{Prim(p[1])} {Identifier(p[0])}" : $"object {Identifier(p[0])}"));
            var rest = sig[(close + 1)..].Trim();
            if (rest.StartsWith(':')) ret = Prim(rest[1..].Trim());
        }
        return (pars, ret);

        static string Prim(string t) => t switch { "Boolean" => "bool", "Integer" => "int", "Real" => "double", "String" => "string", _ => Identifier(t) };
    }

    public static string Identifier(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "Unnamed";
        var sb = new StringBuilder();
        foreach (var ch in name) sb.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        if (char.IsDigit(sb[0])) sb.Insert(0, '_');
        return sb.ToString();
    }

    private static string Pascal(string name)
    {
        var id = Identifier(name);
        return char.ToUpperInvariant(id[0]) + id[1..];
    }
}
