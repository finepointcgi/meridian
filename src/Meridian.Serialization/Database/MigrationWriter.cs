using System.Text;
using Meridian.Core.DataModeling;

namespace Meridian.Serialization.Database;

/// <summary>A migration script with the warnings about steps that can lose data or fail on existing rows.</summary>
public sealed record MigrationScript(string Sql, IReadOnlyList<string> Warnings, int Steps);

/// <summary>
/// ALTER scripts that turn one catalog into another (a baseline, a branch or a live database → the model): new schemas,
/// types, sequences and tables; added, altered and dropped columns; primary keys, unique / check constraints, indexes and
/// foreign keys (dropped first, added last). Destructive steps are marked with a WARNING comment and listed in
/// <see cref="MigrationScript.Warnings"/>. Meridian only writes the script; it never runs it.
/// </summary>
public static class MigrationWriter
{
    public static MigrationScript Generate(DbCatalog before, DbCatalog after, string dialect, string? title = null) =>
        Generate(DbDiff.Compare(before, after), before, after, dialect, title);

    public static MigrationScript Generate(IReadOnlyList<DbChange> changes, DbCatalog before, DbCatalog after, string dialect, string? title = null)
    {
        var sb = new StringBuilder();
        var warnings = new List<string>();
        var steps = 0;
        var d = dialect;
        var qualify = after.Schemas.Count(s => s.Tables.Count > 0) > 1 || before.Schemas.Count(s => s.Tables.Count > 0) > 1
                      || after.Schemas.Any(s => s.Tables.Count > 0 && !IsDefaultSchema(s.Name, d, after.Name));
        string Q(string n) => DdlWriter.Quote(n, d);
        string Name(string schema, string name) => qualify && schema.Length > 0 && d != "sqlite" ? $"{Q(schema)}.{Q(name)}" : Q(name);
        string Go = d == "sqlserver" ? "GO\n" : "";
        void Line(string s) { sb.AppendLine(s); steps++; }
        void Warn(DbChange c, string why)
        {
            var w = $"{c.Describe()}: {why}";
            warnings.Add(w);
            sb.AppendLine($"-- WARNING: {why}");
        }

        sb.AppendLine($"-- {title ?? "Migration script"} ({DbReservedWords.DialectName(d)}), generated by Meridian");
        sb.AppendLine("-- Review it, run it inside a transaction and keep a backup: Meridian never executes DDL against a database.");
        sb.AppendLine();
        if (changes.Count == 0) { sb.AppendLine("-- No differences."); return new MigrationScript(sb.ToString(), warnings, 0); }

        // 1. Drop foreign keys that go away or change (before columns and tables they use are altered).
        foreach (var c in changes.Where(c => c.Type == DbObjectType.ForeignKey && c.Kind is DbChangeKind.Removed or DbChangeKind.Changed))
        {
            var fk = (DbForeignKeyDef)c.Before!;
            if (string.IsNullOrEmpty(fk.Name)) { sb.AppendLine($"-- Foreign key {c.Name} on {c.Table} has no name: drop it by hand"); continue; }
            Line(d == "mysql" ? $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP FOREIGN KEY {Q(fk.Name)};" : d == "sqlite" ? $"-- SQLite can't drop foreign key {fk.Name}: rebuild {c.Table}" : $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP CONSTRAINT {Q(fk.Name)};");
        }
        // Drop indexes and constraints that go away or change.
        foreach (var c in changes.Where(c => c.Type is DbObjectType.Index or DbObjectType.Constraint && c.Kind is DbChangeKind.Removed or DbChangeKind.Changed))
        {
            if (c.Type == DbObjectType.Index)
                Line(d switch
                {
                    "sqlserver" or "mysql" => $"DROP INDEX {Q(c.Name)} ON {Name(c.Schema, c.Table!)};",
                    _ => $"DROP INDEX {(qualify && c.Schema.Length > 0 && d == "postgresql" ? Q(c.Schema) + "." : "")}{Q(c.Name)};",
                });
            else Line(d == "mysql" && ((DbConstraintDef)c.Before!).Type == DbFields.UniqueConstraint ? $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP INDEX {Q(c.Name)};" : $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP CONSTRAINT {Q(c.Name)};");
        }
        foreach (var c in changes.Where(c => c.Type == DbObjectType.PrimaryKey && c.Kind is DbChangeKind.Removed or DbChangeKind.Changed))
        {
            var t = (DbTableDef)c.Before!;
            Line(d == "mysql" ? $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP PRIMARY KEY;" : $"ALTER TABLE {Name(c.Schema, c.Table!)} DROP CONSTRAINT {Q(t.PrimaryKeyName ?? $"{t.Name}_pkey")};");
        }
        if (sb.Length > 0) sb.Append(Go);

        // 2. New schemas, types, sequences and tables (a sub-catalog written by the DDL writer, without foreign keys yet).
        var added = new DbCatalog { Name = after.Name, Dialect = d };
        foreach (var c in changes.Where(c => c.Kind == DbChangeKind.Added))
        {
            switch (c.Type)
            {
                case DbObjectType.Schema: added.Schema(c.Schema); break;
                case DbObjectType.Type: added.Schema(c.Schema).Types.Add((DbTypeDef)c.After!); break;
                case DbObjectType.Sequence: added.Schema(c.Schema).Sequences.Add((DbSequenceDef)c.After!); break;
                case DbObjectType.Table or DbObjectType.View: added.Schema(c.Schema).Tables.Add(Clone((DbTableDef)c.After!)); break;
            }
        }
        if (added.ObjectCount > 0 || added.Schemas.Count > 0)
        {
            foreach (var t in added.AllTables) t.ForeignKeys.Clear();
            var ddl = DdlWriter.Generate(added, d, new DdlOptions { Title = "New objects" });
            sb.AppendLine(string.Join("\n", ddl.Split('\n').Skip(3)).TrimEnd());   // without the header
            sb.AppendLine();
            steps += added.ObjectCount;
            // Their foreign keys are added with the others, last.
            foreach (var s in added.Schemas)
                foreach (var t in s.Tables)
                {
                    var orig = (DbTableDef)changes.First(c => c.Kind == DbChangeKind.Added && c.After is DbTableDef x && DbCatalog.Eq(x.Name, t.Name) && DbCatalog.Eq(c.Schema, s.Name)).After!;
                    t.ForeignKeys.AddRange(orig.ForeignKeys);
                }
        }

        // 3. Columns.
        foreach (var c in changes.Where(c => c.Type == DbObjectType.Column))
        {
            var table = Name(c.Schema, c.Table!);
            switch (c.Kind)
            {
                case DbChangeKind.Added:
                {
                    var col = (DbColumnDef)c.After!;
                    var def = $"{Q(col.Name)} {DbTypes.ForDialect(col.Type, d)}{(col.Default is { Length: > 0 } dv ? $" DEFAULT {dv}" : "")}{(!col.Nullable ? " NOT NULL" : "")}";
                    if (!col.Nullable && col.Default == null && col.Identity == null)
                        Warn(c, "a NOT NULL column without a default fails on a table that has rows; add a default or fill it in first");
                    Line(d switch
                    {
                        "sqlserver" => $"ALTER TABLE {table} ADD {def};",
                        "oracle" => $"ALTER TABLE {table} ADD ({def});",
                        _ => $"ALTER TABLE {table} ADD COLUMN {def};",
                    });
                    if (col.Comment is { Length: > 0 } cc && d is "postgresql" or "oracle") Line($"COMMENT ON COLUMN {table}.{Q(col.Name)} IS {DdlWriter.Literal(cc)};");
                    break;
                }
                case DbChangeKind.Removed:
                    Warn(c, "dropping a column deletes its data");
                    Line(d == "sqlite" ? $"ALTER TABLE {table} DROP COLUMN {Q(c.Name)};  -- SQLite 3.35+" : $"ALTER TABLE {table} DROP COLUMN {Q(c.Name)};");
                    break;
                case DbChangeKind.Changed:
                {
                    var col = (DbColumnDef)c.After!;
                    var type = DbTypes.ForDialect(col.Type, d);
                    foreach (var f in c.Fields)
                    {
                        switch (f.Key)
                        {
                            case "type":
                                Warn(c, $"changing the type from {f.Before} to {f.After} can fail or truncate existing values");
                                Line(d switch
                                {
                                    "postgresql" => $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} TYPE {type} USING {Q(col.Name)}::{type};",
                                    "sqlserver" => $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} {type}{(col.Nullable ? " NULL" : " NOT NULL")};",
                                    "mysql" => $"ALTER TABLE {table} MODIFY COLUMN {Q(col.Name)} {type}{(col.Nullable ? " NULL" : " NOT NULL")};",
                                    "oracle" => $"ALTER TABLE {table} MODIFY ({Q(col.Name)} {type});",
                                    _ => $"-- SQLite can't change the type of {c.Table}.{col.Name}: rebuild the table",
                                });
                                break;
                            case "nullable":
                                var notNull = f.After == "false";
                                if (notNull) Warn(c, "SET NOT NULL fails while the column holds NULLs");
                                if (c.Fields.Any(x => x.Key == "type") && d is "sqlserver" or "mysql") break;   // already part of the type change
                                Line(d switch
                                {
                                    "postgresql" => $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} {(notNull ? "SET" : "DROP")} NOT NULL;",
                                    "sqlserver" => $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} {type} {(notNull ? "NOT NULL" : "NULL")};",
                                    "mysql" => $"ALTER TABLE {table} MODIFY COLUMN {Q(col.Name)} {type} {(notNull ? "NOT NULL" : "NULL")};",
                                    "oracle" => $"ALTER TABLE {table} MODIFY ({Q(col.Name)} {(notNull ? "NOT NULL" : "NULL")});",
                                    _ => $"-- SQLite can't change NULL / NOT NULL of {c.Table}.{col.Name}: rebuild the table",
                                });
                                break;
                            case "default":
                                Line(d switch
                                {
                                    "sqlserver" => col.Default is { Length: > 0 } sdv ? $"ALTER TABLE {table} ADD DEFAULT {sdv} FOR {Q(col.Name)};  -- drop the old default constraint first" : $"-- Drop the default constraint of {c.Table}.{col.Name} by name",
                                    "oracle" => $"ALTER TABLE {table} MODIFY ({Q(col.Name)} DEFAULT {(col.Default is { Length: > 0 } odv ? odv : "NULL")});",
                                    "sqlite" => $"-- SQLite can't change the default of {c.Table}.{col.Name}: rebuild the table",
                                    _ => col.Default is { Length: > 0 } pdv ? $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} SET DEFAULT {pdv};" : $"ALTER TABLE {table} ALTER COLUMN {Q(col.Name)} DROP DEFAULT;",
                                });
                                break;
                            case "comment" when d is "postgresql" or "oracle":
                                Line($"COMMENT ON COLUMN {table}.{Q(col.Name)} IS {(col.Comment is { Length: > 0 } cm ? DdlWriter.Literal(cm) : "NULL")};");
                                break;
                            case "unique":
                                if (f.After == "true") Line($"ALTER TABLE {table} ADD CONSTRAINT {Q($"uq_{c.Table}_{col.Name}")} UNIQUE ({Q(col.Name)});");
                                else sb.AppendLine($"-- {c.Table}.{col.Name} is no longer unique: drop its unique constraint by name");
                                break;
                            default:
                                sb.AppendLine($"-- {c.Table}.{col.Name}: {f.Key} changed from {f.Before ?? "(none)"} to {f.After ?? "(none)"} — not scripted");
                                break;
                        }
                    }
                    break;
                }
            }
        }

        // 4. Tables, views and other objects that go away.
        foreach (var c in changes.Where(c => c.Kind == DbChangeKind.Removed && c.Type is DbObjectType.Table or DbObjectType.View or DbObjectType.Sequence or DbObjectType.Type or DbObjectType.Routine))
        {
            switch (c.Type)
            {
                case DbObjectType.Table:
                    Warn(c, "dropping a table deletes its data");
                    Line($"DROP TABLE {Name(c.Schema, c.Name)};");
                    break;
                case DbObjectType.View:
                    Line($"DROP {(((DbTableDef)c.Before!).Kind == DbFields.MaterializedView && d is "postgresql" or "oracle" ? "MATERIALIZED " : "")}VIEW {Name(c.Schema, c.Name)};");
                    break;
                case DbObjectType.Sequence:
                    if (d is not ("mysql" or "sqlite")) Line($"DROP SEQUENCE {Name(c.Schema, c.Name)};");
                    break;
                case DbObjectType.Type:
                    if (d == "postgresql") { Warn(c, "dropping a type fails while columns use it"); Line($"DROP {(((DbTypeDef)c.Before!).Kind == "enum" ? "TYPE" : "DOMAIN")} {Name(c.Schema, c.Name)};"); }
                    break;
                case DbObjectType.Routine:
                    sb.AppendLine($"-- Routine {c.Name} is gone from the model: drop it by hand if intended");
                    break;
            }
        }
        foreach (var c in changes.Where(c => c.Kind == DbChangeKind.Changed && c.Type is DbObjectType.View))
        {
            var v = (DbTableDef)c.After!;
            if (v.Definition is { Length: > 0 } def)
                Line(d switch
                {
                    "postgresql" when v.Kind != DbFields.MaterializedView => $"CREATE OR REPLACE VIEW {Name(c.Schema, v.Name)} AS {def.TrimEnd(';')};",
                    "sqlserver" => $"CREATE OR ALTER VIEW {Name(c.Schema, v.Name)} AS {def.TrimEnd(';')};",
                    "mysql" or "oracle" => $"CREATE OR REPLACE VIEW {Name(c.Schema, v.Name)} AS {def.TrimEnd(';')};",
                    _ => $"DROP VIEW {Name(c.Schema, v.Name)};\nCREATE VIEW {Name(c.Schema, v.Name)} AS {def.TrimEnd(';')};",
                });
        }
        foreach (var c in changes.Where(c => c.Kind == DbChangeKind.Changed && c.Type is DbObjectType.Table or DbObjectType.Sequence or DbObjectType.Type))
            foreach (var f in c.Fields)
            {
                if (f.Key == "comment" && c.Type == DbObjectType.Table && d is "postgresql" or "oracle")
                    Line($"COMMENT ON TABLE {Name(c.Schema, c.Name)} IS {(f.After is { Length: > 0 } tc ? DdlWriter.Literal(tc) : "NULL")};");
                else if (c.Type == DbObjectType.Type && f.Key == "values" && d == "postgresql")
                {
                    var before2 = (DbTypeDef)c.Before!; var after2 = (DbTypeDef)c.After!;
                    foreach (var v in after2.Values.Where(v => !before2.Values.Contains(v))) Line($"ALTER TYPE {Name(c.Schema, c.Name)} ADD VALUE {DdlWriter.Literal(v)};");
                    if (before2.Values.Any(v => !after2.Values.Contains(v))) Warn(c, "enum values can't be removed in PostgreSQL without recreating the type");
                }
                else if (c.Type == DbObjectType.Sequence && d is not ("mysql" or "sqlite"))
                    Line(f.Key == "start" ? $"ALTER SEQUENCE {Name(c.Schema, c.Name)} RESTART WITH {f.After};" : $"ALTER SEQUENCE {Name(c.Schema, c.Name)} INCREMENT BY {f.After};");
                else sb.AppendLine($"-- {c.Label}: {f.Key} changed — not scripted");
            }
        if (sb.Length > 0) sb.Append(Go);

        // 5. Primary keys, unique / check constraints and indexes that are new or changed.
        foreach (var c in changes.Where(c => c.Type == DbObjectType.PrimaryKey && c.Kind is DbChangeKind.Added or DbChangeKind.Changed))
        {
            var t = (DbTableDef)c.After!;
            Line($"ALTER TABLE {Name(c.Schema, c.Table!)} ADD {(t.PrimaryKeyName is { Length: > 0 } pk ? $"CONSTRAINT {Q(pk)} " : "")}PRIMARY KEY ({string.Join(", ", t.PrimaryKey.Select(Q))});");
        }
        foreach (var c in changes.Where(c => c.Type == DbObjectType.Constraint && c.Kind is DbChangeKind.Added or DbChangeKind.Changed))
        {
            var k = (DbConstraintDef)c.After!;
            Line(k.Type == DbFields.CheckConstraint
                ? $"ALTER TABLE {Name(c.Schema, c.Table!)} ADD CONSTRAINT {Q(k.Name)} CHECK ({k.Expression});"
                : $"ALTER TABLE {Name(c.Schema, c.Table!)} ADD CONSTRAINT {Q(k.Name)} UNIQUE ({string.Join(", ", k.Columns.Select(Q))});");
        }
        foreach (var c in changes.Where(c => c.Type == DbObjectType.Index && c.Kind is DbChangeKind.Added or DbChangeKind.Changed))
        {
            var ix = (DbIndexDef)c.After!;
            var cols = string.Join(", ", ix.Columns.Select(x => x.All(ch => char.IsLetterOrDigit(ch) || ch == '_') ? Q(x) : x));
            Line($"CREATE{(ix.Unique ? " UNIQUE" : "")} INDEX {Q(ix.Name)} ON {Name(c.Schema, c.Table!)}{(d == "postgresql" && ix.Method is { Length: > 0 } m && m != "btree" ? $" USING {m}" : "")} ({cols}){(ix.Where is { Length: > 0 } w && d is "postgresql" or "sqlite" or "sqlserver" ? $" WHERE {w}" : "")};");
        }

        // 6. Foreign keys, last: new tables' keys, then added or changed ones.
        var fkLines = new List<string>();
        foreach (var s in added.Schemas)
            foreach (var t in s.Tables.Where(t => !t.IsView))
                foreach (var fk in t.ForeignKeys) fkLines.Add(AddFk(s.Name, t.Name, fk));
        foreach (var c in changes.Where(c => c.Type == DbObjectType.ForeignKey && c.Kind is DbChangeKind.Added or DbChangeKind.Changed))
            fkLines.Add(AddFk(c.Schema, c.Table!, (DbForeignKeyDef)c.After!));
        if (fkLines.Count > 0)
        {
            sb.AppendLine("-- Foreign keys");
            foreach (var l in fkLines) Line(l);
        }
        foreach (var c in changes.Where(c => c.Type is DbObjectType.Trigger or DbObjectType.Routine && c.Kind != DbChangeKind.Removed))
            sb.AppendLine($"-- {c.Describe()} — triggers and routines are not scripted (signatures only in the model)");
        return new MigrationScript(sb.ToString(), warnings, steps);

        string AddFk(string schema, string table, DbForeignKeyDef fk)
        {
            if (d == "sqlite") return $"-- SQLite can't add foreign key {fk.Name ?? string.Join(",", fk.Columns)} to {table}: rebuild the table";
            var refCols = fk.RefColumns.Count > 0 ? fk.RefColumns : after.FindTable(fk.RefSchema ?? schema, fk.RefTable)?.PrimaryKey ?? [];
            var sql = new StringBuilder($"ALTER TABLE {Name(schema, table)} ADD ");
            if (fk.Name is { Length: > 0 } n) sql.Append($"CONSTRAINT {Q(n)} ");
            sql.Append($"FOREIGN KEY ({string.Join(", ", fk.Columns.Select(Q))}) REFERENCES {Name(fk.RefSchema ?? schema, fk.RefTable)}");
            if (refCols.Count > 0) sql.Append($" ({string.Join(", ", refCols.Select(Q))})");
            if (fk.OnDelete is { Length: > 0 } od) sql.Append($" ON DELETE {od}");
            if (fk.OnUpdate is { Length: > 0 } ou && d != "oracle") sql.Append($" ON UPDATE {ou}");
            return sql.Append(';').ToString();
        }
    }

    private static bool IsDefaultSchema(string schema, string d, string catalog) => schema.Length == 0 || d switch
    {
        "postgresql" => schema.Equals("public", StringComparison.OrdinalIgnoreCase),
        "sqlserver" => schema.Equals("dbo", StringComparison.OrdinalIgnoreCase),
        "sqlite" => true,
        _ => schema.Equals(catalog, StringComparison.OrdinalIgnoreCase) || schema == "default",
    };

    private static DbTableDef Clone(DbTableDef t)
    {
        var c = new DbTableDef { Name = t.Name, Kind = t.Kind, Comment = t.Comment, Definition = t.Definition, PrimaryKeyName = t.PrimaryKeyName };
        c.Columns.AddRange(t.Columns);
        c.PrimaryKey.AddRange(t.PrimaryKey);
        c.ForeignKeys.AddRange(t.ForeignKeys);
        c.Indexes.AddRange(t.Indexes);
        c.Constraints.AddRange(t.Constraints);
        c.Triggers.AddRange(t.Triggers);
        return c;
    }
}
