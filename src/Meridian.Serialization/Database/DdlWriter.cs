using System.Text;
using System.Text.RegularExpressions;
using Meridian.Core.DataModeling;

namespace Meridian.Serialization.Database;

public sealed class DdlOptions
{
    /// <summary>Quote every identifier (otherwise only names that need it: reserved words, odd characters, mixed case in PostgreSQL).</summary>
    public bool QuoteAll { get; init; }
    /// <summary>Write table and column comments (COMMENT ON, extended properties, MySQL COMMENT).</summary>
    public bool Comments { get; init; } = true;
    /// <summary>Write indexes.</summary>
    public bool Indexes { get; init; } = true;
    /// <summary>Header line naming what was generated.</summary>
    public string? Title { get; init; }
}

/// <summary>
/// DDL from a <see cref="DbCatalog"/> for PostgreSQL, SQL Server, MySQL, SQLite or Oracle: schemas, types, sequences, tables
/// in dependency order, indexes, then foreign keys last (inline for SQLite, which can't add them later), views and comments.
/// Routines and triggers follow with their bodies (in the dialect they were written in: a body from another dialect is listed
/// as a comment instead). The script is for review; Meridian never runs it.
/// </summary>
public static partial class DdlWriter
{
    public static string Generate(DbCatalog catalog, string dialect, DdlOptions? options = null)
    {
        options ??= new DdlOptions();
        var w = new Writer(catalog, dialect, options);
        return w.Run();
    }

    [GeneratedRegex(@"^[A-Za-z_][A-Za-z0-9_]*$")]
    private static partial Regex Simple();

    /// <summary>Quotes an identifier for <paramref name="dialect"/> when it needs it (or always).</summary>
    public static string Quote(string name, string dialect, bool always = false)
    {
        var needs = always || !Simple().IsMatch(name) || DbReservedWords.IsReserved(name, dialect) || dialect == "postgresql" && name != name.ToLowerInvariant();
        if (!needs) return name;
        return dialect switch
        {
            "mysql" => $"`{name.Replace("`", "``")}`",
            "sqlserver" => $"[{name.Replace("]", "]]")}]",
            _ => $"\"{name.Replace("\"", "\"\"")}\"",
        };
    }

    public static string Literal(string s) => "'" + s.Replace("'", "''") + "'";

    /// <summary>Tables ordered so that referenced tables come first (cycles keep their original order).</summary>
    public static List<(DbSchemaDef Schema, DbTableDef Table)> DependencyOrder(DbCatalog c)
    {
        var all = c.Schemas.SelectMany(s => s.Tables.Where(t => !t.IsView).Select(t => (s, t))).ToList();
        var result = new List<(DbSchemaDef, DbTableDef)>();
        var state = new Dictionary<DbTableDef, int>(ReferenceEqualityComparer.Instance);
        void Visit((DbSchemaDef S, DbTableDef T) x)
        {
            if (state.TryGetValue(x.T, out var st)) return;   // done, or on the stack (cycle)
            state[x.T] = 1;
            foreach (var fk in x.T.ForeignKeys)
                if (c.FindTable(fk.RefSchema ?? x.S.Name, fk.RefTable) is { } dep && !ReferenceEquals(dep, x.T) && !dep.IsView)
                    Visit((c.Schemas.First(s => s.Tables.Contains(dep)), dep));
            state[x.T] = 2;
            result.Add(x);
        }
        foreach (var x in all.OrderBy(x => x.s.Name, StringComparer.OrdinalIgnoreCase).ThenBy(x => x.t.Name, StringComparer.OrdinalIgnoreCase)) Visit(x);
        return result;
    }

    private sealed class Writer(DbCatalog c, string d, DdlOptions o)
    {
        private readonly StringBuilder _sb = new();
        private readonly bool _qualify = Qualifies(c, d);

        private static bool Qualifies(DbCatalog c, string d)
        {
            var used = c.Schemas.Where(s => s.Tables.Count + s.Sequences.Count + s.Types.Count > 0).ToList();
            if (d is "sqlite") return false;
            if (used.Count > 1) return true;
            return used.Count == 1 && used[0].Name.Length > 0 && !IsDefault(used[0].Name, d, c.Name);
        }

        private static bool IsDefault(string schema, string d, string catalog) => schema.Length == 0 || d switch
        {
            "postgresql" => schema.Equals("public", StringComparison.OrdinalIgnoreCase),
            "sqlserver" => schema.Equals("dbo", StringComparison.OrdinalIgnoreCase),
            "sqlite" => true,
            _ => schema.Equals(catalog, StringComparison.OrdinalIgnoreCase) || schema == "default",
        };

        private string Q(string n) => Quote(n, d, o.QuoteAll);
        private string Name(string schema, string name) => _qualify && schema.Length > 0 ? $"{Q(schema)}.{Q(name)}" : Q(name);
        private string Go => d == "sqlserver" ? "GO\n" : "";

        public string Run()
        {
            _sb.AppendLine($"-- {o.Title ?? $"Generated by Meridian from '{c.Name}'"} ({DbReservedWords.DialectName(d)})");
            _sb.AppendLine("-- Review before running: Meridian generates scripts and never executes DDL against a database.");
            _sb.AppendLine();
            Schemas();
            Types();
            Sequences();
            var ordered = DependencyOrder(c);
            foreach (var (s, t) in ordered) Table(s, t);
            if (o.Indexes) foreach (var (s, t) in ordered) Indexes(s, t);
            if (d != "sqlite")
            {
                var fks = ordered.SelectMany(x => x.Table.ForeignKeys.Select(fk => (x.Schema, x.Table, fk))).ToList();
                if (fks.Count > 0) _sb.AppendLine("-- Foreign keys");
                foreach (var (s, t, fk) in fks) _sb.AppendLine($"ALTER TABLE {Name(s.Name, t.Name)} ADD {ForeignKey(s, fk)};");
                if (fks.Count > 0) _sb.Append(Go).AppendLine();   // T-SQL: CREATE VIEW must start a batch
            }
            foreach (var s in c.Schemas)
                foreach (var v in s.Tables.Where(t => t.IsView)) View(s, v);
            Routines();
            Triggers(ordered);
            return _sb.ToString();
        }

        private void Schemas()
        {
            if (!_qualify) return;
            foreach (var s in c.Schemas.Where(s => s.Name.Length > 0 && !IsDefault(s.Name, d, c.Name)))
            {
                switch (d)
                {
                    case "postgresql": _sb.AppendLine($"CREATE SCHEMA IF NOT EXISTS {Q(s.Name)};"); break;
                    case "sqlserver": _sb.AppendLine($"IF SCHEMA_ID(N{Literal(s.Name)}) IS NULL EXEC(N'CREATE SCHEMA {Q(s.Name).Replace("'", "''")}');"); break;
                    case "mysql": _sb.AppendLine($"CREATE DATABASE IF NOT EXISTS {Q(s.Name)};"); break;
                    case "oracle": _sb.AppendLine($"-- Schema {s.Name}: create the user / schema first (CREATE USER {Q(s.Name)} …)"); break;
                }
                if (o.Comments && s.Comment is { Length: > 0 } sc && d == "postgresql") _sb.AppendLine($"COMMENT ON SCHEMA {Q(s.Name)} IS {Literal(sc)};");
            }
            _sb.Append(Go).AppendLine();
        }

        private void Types()
        {
            var any = false;
            foreach (var s in c.Schemas)
                foreach (var t in s.Types)
                {
                    any = true;
                    if (d == "postgresql")
                    {
                        if (t.Kind == "enum") _sb.AppendLine($"CREATE TYPE {Name(s.Name, t.Name)} AS ENUM ({string.Join(", ", t.Values.Select(Literal))});");
                        else _sb.AppendLine($"CREATE DOMAIN {Name(s.Name, t.Name)} AS {DbTypes.ForDialect(t.BaseType, d)}{(t.NotNull ? " NOT NULL" : "")}{(t.Check is { Length: > 0 } ck ? $" CHECK ({ck})" : "")};");
                        if (o.Comments && t.Comment is { Length: > 0 } tc) _sb.AppendLine($"COMMENT ON {(t.Kind == "enum" ? "TYPE" : "DOMAIN")} {Name(s.Name, t.Name)} IS {Literal(tc)};");
                    }
                    else if (d == "sqlserver" && t.Kind == "domain") _sb.AppendLine($"CREATE TYPE {Name(s.Name, t.Name)} FROM {DbTypes.ForDialect(t.BaseType, d)}{(t.NotNull ? " NOT NULL" : "")};");
                    else _sb.AppendLine($"-- {(t.Kind == "enum" ? "Enum" : "Domain")} {t.Name}: {(t.Kind == "enum" ? string.Join(", ", t.Values) : t.BaseType)} (written into the columns that use it)");
                }
            if (any) _sb.Append(Go).AppendLine();
        }

        private void Sequences()
        {
            var any = false;
            foreach (var s in c.Schemas)
                foreach (var q in s.Sequences)
                {
                    any = true;
                    if (d is "mysql" or "sqlite") { _sb.AppendLine($"-- Sequence {q.Name}: not supported by {DbReservedWords.DialectName(d)} (use AUTO_INCREMENT / AUTOINCREMENT columns)"); continue; }
                    var line = new StringBuilder($"CREATE SEQUENCE {Name(s.Name, q.Name)}");
                    if (q.Type is { Length: > 0 } st && d != "oracle") line.Append($" AS {DbTypes.ForDialect(st, d)}");
                    if (q.Start is { Length: > 0 } start) line.Append($" START WITH {start}");
                    if (q.Increment is { Length: > 0 } inc) line.Append($" INCREMENT BY {inc}");
                    if (q.Min is { Length: > 0 } min) line.Append($" MINVALUE {min}");
                    if (q.Max is { Length: > 0 } max) line.Append($" MAXVALUE {max}");
                    if (q.Cycle) line.Append(" CYCLE");
                    _sb.AppendLine(line.Append(';').ToString());
                }
            if (any) _sb.Append(Go).AppendLine();
        }

        private DbTypeDef? TypeNamed(string type) =>
            c.Schemas.SelectMany(s => s.Types).FirstOrDefault(t => DbCatalog.Eq(t.Name, type) || type.EndsWith("." + t.Name, StringComparison.OrdinalIgnoreCase));

        /// <summary>A column type for the dialect; enum and domain types become their base type elsewhere than PostgreSQL.</summary>
        private string ColumnType(DbColumnDef col, List<string> extraChecks)
        {
            if (d != "postgresql" && TypeNamed(col.Type) is { } td)
            {
                if (td.Kind == "domain") return d == "sqlserver" ? Q(td.Name) : DbTypes.ForDialect(td.BaseType, d);
                if (d == "mysql") return $"ENUM({string.Join(", ", td.Values.Select(Literal))})";
                extraChecks.Add($"CHECK ({Q(col.Name)} IN ({string.Join(", ", td.Values.Select(Literal))}))");
                return DbTypes.ForDialect($"varchar({Math.Max(1, td.Values.DefaultIfEmpty("").Max(v => v.Length))})", d);
            }
            if (d == "sqlite" && col.Identity != null) return "integer";
            if (d == "sqlite" && col.Type.Length == 0) return "";   // SQLite allows columns without a type
            if (col.Type.Equals("computed", StringComparison.OrdinalIgnoreCase)) return d == "sqlserver" ? "" : "text";   // T-SQL computed columns have no type
            return DbTypes.ForDialect(col.Type, d);
        }

        private void Table(DbSchemaDef s, DbTableDef t)
        {
            var lines = new List<string>();
            var checks = new List<string>();
            // serial / bigserial are auto-numbered: other dialects get their identity syntax.
            string? IdentityOf(DbColumnDef c) => c.Identity ?? (d != "postgresql" && DbTypes.IsSerial(c.Type) ? "always" : null);
            var inlinePkAutoinc = d == "sqlite" && t.PrimaryKey.Count == 1 && t.FindColumn(t.PrimaryKey[0]) is { } pkCol && IdentityOf(pkCol) != null;
            foreach (var col in t.Columns)
            {
                var identity = IdentityOf(col);
                var line = new StringBuilder($"    {Q(col.Name)} {ColumnType(col, checks)}".TrimEnd());
                if (col.Generated is { Length: > 0 } gen)
                    line.Append(d == "sqlserver" ? "" : " GENERATED ALWAYS").Append($" AS ({gen})").Append(d == "postgresql" ? " STORED" : d == "sqlserver" ? " PERSISTED" : "");
                else if (identity != null)
                    line.Append(d switch
                    {
                        "sqlserver" => " IDENTITY(1,1)",
                        "mysql" => " AUTO_INCREMENT",
                        "sqlite" => inlinePkAutoinc && t.IsPrimaryKey(col.Name) ? " PRIMARY KEY AUTOINCREMENT" : "",
                        _ => identity == "byDefault" ? " GENERATED BY DEFAULT AS IDENTITY" : " GENERATED ALWAYS AS IDENTITY",
                    });
                if (col.Collation is { Length: > 0 } coll) line.Append($" COLLATE {coll}");
                if (col.Default is { Length: > 0 } dv && col.Generated == null) line.Append($" DEFAULT {dv}");
                if (!col.Nullable || t.IsPrimaryKey(col.Name)) line.Append(" NOT NULL");
                if (col.Unique && !t.IsPrimaryKey(col.Name)) line.Append(" UNIQUE");
                if (d == "mysql" && o.Comments && col.Comment is { Length: > 0 } cc) line.Append($" COMMENT {Literal(cc)}");
                lines.Add(line.ToString());
            }
            if (t.PrimaryKey.Count > 0 && !inlinePkAutoinc)
                lines.Add($"    {(t.PrimaryKeyName is { Length: > 0 } pkn ? $"CONSTRAINT {Q(pkn)} " : "")}PRIMARY KEY ({string.Join(", ", t.PrimaryKey.Select(Q))})");
            foreach (var u in t.Constraints.Where(x => x.Type == DbFields.UniqueConstraint))
                lines.Add($"    CONSTRAINT {Q(u.Name)} UNIQUE ({string.Join(", ", u.Columns.Select(Q))})");
            foreach (var ck in t.Constraints.Where(x => x.Type == DbFields.CheckConstraint))
                lines.Add($"    CONSTRAINT {Q(ck.Name)} CHECK ({ck.Expression})");
            lines.AddRange(checks.Select(x => "    " + x));
            if (d == "sqlite") foreach (var fk in t.ForeignKeys) lines.Add("    " + ForeignKey(s, fk));
            _sb.AppendLine($"CREATE TABLE {Name(s.Name, t.Name)} (");
            _sb.AppendLine(string.Join(",\n", lines));
            _sb.Append(')');
            if (d == "mysql" && o.Comments && t.Comment is { Length: > 0 } mc) _sb.Append($" COMMENT={Literal(mc)}");
            _sb.AppendLine(";");
            Comments(s, t);
            _sb.Append(Go).AppendLine();
        }

        private static string OneLine(string s) { var x = Regex.Replace(s, @"\s+", " ").Trim(); return x.Length > 100 ? x[..97] + "…" : x; }

        private void Comments(DbSchemaDef s, DbTableDef t)
        {
            if (!o.Comments) return;
            var table = Name(s.Name, t.Name);
            var schema = s.Name.Length > 0 && !IsDefault(s.Name, d, c.Name) ? s.Name : d == "sqlserver" ? "dbo" : s.Name;
            switch (d)
            {
                case "postgresql" or "oracle":
                    if (t.Comment is { Length: > 0 } tc) _sb.AppendLine($"COMMENT ON {(t.Kind == DbFields.MaterializedView && d == "postgresql" ? "MATERIALIZED VIEW" : t.IsView && d == "postgresql" ? "VIEW" : "TABLE")} {table} IS {Literal(tc)};");
                    foreach (var col in t.Columns.Where(x => x.Comment is { Length: > 0 }))
                        _sb.AppendLine($"COMMENT ON COLUMN {table}.{Q(col.Name)} IS {Literal(col.Comment!)};");
                    break;
                case "sqlserver":
                    var level1 = t.IsView ? "VIEW" : "TABLE";
                    if (t.Comment is { Length: > 0 } stc)
                        _sb.AppendLine($"EXEC sp_addextendedproperty N'MS_Description', N{Literal(stc)}, N'SCHEMA', N{Literal(schema)}, N'{level1}', N{Literal(t.Name)};");
                    foreach (var col in t.Columns.Where(x => x.Comment is { Length: > 0 }))
                        _sb.AppendLine($"EXEC sp_addextendedproperty N'MS_Description', N{Literal(col.Comment!)}, N'SCHEMA', N{Literal(schema)}, N'{level1}', N{Literal(t.Name)}, N'COLUMN', N{Literal(col.Name)};");
                    break;
                case "sqlite":
                    if (t.Comment is { Length: > 0 } ltc) _sb.AppendLine($"-- {t.Name}: {OneLine(ltc)}");
                    break;
            }
        }

        private void Indexes(DbSchemaDef s, DbTableDef t)
        {
            foreach (var ix in t.Indexes)
            {
                var method = ix.Method?.ToLowerInvariant();
                var kind = d switch
                {
                    "sqlserver" when method is "clustered" => " CLUSTERED",
                    "mysql" when method is "fulltext" or "spatial" => " " + method.ToUpperInvariant(),
                    _ => "",
                };
                var usingClause = d == "postgresql" && method is { Length: > 0 } and not "btree" and not "clustered" ? $" USING {method}" : "";
                var cols = string.Join(", ", ix.Columns.Select(x => Simple().IsMatch(x) ? Q(x) : x));
                var where = ix.Where is { Length: > 0 } wh && d is "postgresql" or "sqlite" or "sqlserver" ? $" WHERE {wh}" : "";
                var table = Name(s.Name, t.Name);
                var name = d == "postgresql" || d == "oracle" ? (_qualify && s.Name.Length > 0 ? $"{Q(s.Name)}.{Q(ix.Name)}" : Q(ix.Name)) : Q(ix.Name);
                if (d == "postgresql") name = Q(ix.Name);   // PostgreSQL: the index lives in the table's schema
                _sb.AppendLine($"CREATE{(ix.Unique ? " UNIQUE" : "")}{kind} INDEX {name} ON {table}{usingClause} ({cols}){where};");
            }
            if (t.Indexes.Count > 0) _sb.Append(Go).AppendLine();
        }

        private string ForeignKey(DbSchemaDef s, DbForeignKeyDef fk)
        {
            var target = c.FindTable(fk.RefSchema ?? s.Name, fk.RefTable);
            var refSchema = fk.RefSchema ?? (target != null ? c.Schemas.First(x => x.Tables.Contains(target)).Name : s.Name);
            var refCols = fk.RefColumns.Count > 0 ? fk.RefColumns : target?.PrimaryKey ?? [];
            var sb = new StringBuilder();
            if (fk.Name is { Length: > 0 } n) sb.Append($"CONSTRAINT {Q(n)} ");
            sb.Append($"FOREIGN KEY ({string.Join(", ", fk.Columns.Select(Q))}) REFERENCES {Name(refSchema, fk.RefTable)}");
            if (refCols.Count > 0) sb.Append($" ({string.Join(", ", refCols.Select(Q))})");
            if (fk.OnDelete is { Length: > 0 } od && !(d == "oracle" && od is "RESTRICT" or "NO ACTION" or "SET DEFAULT")) sb.Append($" ON DELETE {od}");
            if (fk.OnUpdate is { Length: > 0 } ou && d != "oracle") sb.Append($" ON UPDATE {ou}");
            return sb.ToString();
        }

        private void View(DbSchemaDef s, DbTableDef v)
        {
            var mat = v.Kind == DbFields.MaterializedView && d is "postgresql" or "oracle";
            if (v.Kind == DbFields.MaterializedView && !mat) _sb.AppendLine($"-- {v.Name} is a materialized view in the model; {DbReservedWords.DialectName(d)} gets a plain view.");
            var definition = v.Definition is { Length: > 0 } def ? def.Trim().TrimEnd(';')
                : $"SELECT {(v.Columns.Count > 0 ? string.Join(", ", v.Columns.Select(x => $"NULL AS {Q(x.Name)}")) : "1 AS placeholder")}  -- no definition in the model";
            _sb.AppendLine($"CREATE {(mat ? "MATERIALIZED " : "")}VIEW {Name(s.Name, v.Name)} AS");
            _sb.AppendLine(definition + ";");
            Comments(s, v);
            _sb.Append(Go).AppendLine();
        }

        /// <summary>SQL Server: CREATE OR ALTER of a routine or trigger must start a batch.</summary>
        private void NewBatch()
        {
            if (d == "sqlserver" && !_sb.ToString().TrimEnd().EndsWith("GO", StringComparison.Ordinal)) _sb.AppendLine("GO");
        }

        /// <summary>Bodies are only written for the dialect they came from (or when the catalog's dialect is unknown).</summary>
        private bool SameDialect => c.Dialect.Length == 0 || c.Dialect == d;

        private void Routines()
        {
            var all = c.Schemas.SelectMany(s => s.Routines.Select(r => (s, r))).ToList();
            if (all.Count == 0) return;
            var listed = all.Where(x => !SameDialect || !DbModuleSql.CanCreate(x.r, d)).ToList();
            if (listed.Count > 0)
            {
                _sb.AppendLine(SameDialect ? "-- Routines without a body in the model (signatures only):" : $"-- Routines written for {DbReservedWords.DialectName(c.Dialect)} (bodies are not translated):");
                foreach (var (s, r) in listed)
                    _sb.AppendLine($"--   {r.Kind} {(s.Name.Length > 0 ? s.Name + "." : "")}{r.Name}{r.Signature}{(r.Returns is { Length: > 0 } ret ? " RETURNS " + ret : "")}");
                _sb.AppendLine();
            }
            if (all.Count > listed.Count) NewBatch();
            foreach (var (s, r) in all.Except(listed))
            {
                _sb.Append(DbModuleSql.CreateRoutine(Name(s.Name, r.Name), r, d, replace: false));
                if (d != "sqlserver") _sb.AppendLine();
            }
        }

        private void Triggers(List<(DbSchemaDef Schema, DbTableDef Table)> ordered)
        {
            var all = ordered.Concat(c.Schemas.SelectMany(s => s.Tables.Where(t => t.IsView).Select(t => (s, t))))
                .SelectMany(x => x.Item2.Triggers.Select(tg => (Schema: x.Item1, Table: x.Item2, Trigger: tg))).ToList();
            if (all.Count == 0) return;
            NewBatch();
            _sb.AppendLine("-- Triggers");
            foreach (var (s, t, tg) in all)
            {
                if (!SameDialect)
                {
                    _sb.AppendLine($"-- Trigger {tg.Name} on {t.Name}: {tg.Timing} {tg.Events}{(tg.Level is { Length: > 0 } lv ? $" FOR EACH {lv}" : "")} (written for {DbReservedWords.DialectName(c.Dialect)}; not generated)");
                    continue;
                }
                var name = d is "sqlserver" or "oracle" or "mysql" ? Name(s.Name, tg.Name) : Q(tg.Name);
                _sb.Append(DbModuleSql.CreateTrigger(name, Name(s.Name, t.Name), tg, d, replace: false));
                if (d != "sqlserver") _sb.AppendLine();
            }
        }
    }
}
