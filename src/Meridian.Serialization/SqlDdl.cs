using Meridian.Core.DataModeling;
using Meridian.Core.Model;
using Meridian.Serialization.Database;

namespace Meridian.Serialization;

public enum SqlDialect { PostgreSql, MySql, SqlServer, Sqlite, Oracle }

/// <summary>
/// Data modelling entry points kept for existing callers: DDL for the whole model, and the flat CREATE TABLE import into a
/// package. The full pipeline lives in <see cref="DdlParser"/>, <see cref="DdlWriter"/>, <see cref="MigrationWriter"/> and
/// <see cref="DbImport"/>.
/// </summary>
public static class SqlDdl
{
    /// <summary>DDL for every table in the model (identifiers quoted), dependency ordered, foreign keys last.</summary>
    public static string Generate(ModelRepository m, SqlDialect dialect) =>
        DdlWriter.Generate(DbExtract.FromModel(m, m.Root).Catalog, DatabaseFiles.DialectOf(dialect), new DdlOptions { QuoteAll = true, Title = $"Generated by Meridian from '{m.Root.Name}'" });

    /// <summary>DDL for a database, schema, subject area or package (or a selection of tables in it).</summary>
    public static string Generate(ModelRepository m, Element scope, SqlDialect dialect, IEnumerable<Element>? tables = null, DdlOptions? options = null) =>
        DdlWriter.Generate(DbExtract.FromModel(m, scope, tables).Catalog, DatabaseFiles.DialectOf(dialect), options);

    /// <summary>
    /// Reverse-engineers a script into tables, columns and foreign keys directly inside <paramref name="target"/> (no database or
    /// schema packages; use <see cref="DbImport"/> for a full import). Tables with the same name are updated.
    /// </summary>
    public static (int Tables, int ForeignKeys) Import(ModelRepository m, Element target, string ddl, Diagram? diagram = null)
    {
        var catalog = DdlParser.Parse(ddl);
        using (m.History.Transaction("Import DDL"))
        {
            var w = new DbModelWriter(m, target, "");
            var tables = new Dictionary<string, Element>(StringComparer.OrdinalIgnoreCase);
            foreach (var s in catalog.Schemas)
                foreach (var t in s.Tables)
                {
                    var existing = m.OfKind(ElementKind.Table).FirstOrDefault(x => x.Name.Equals(t.Name, StringComparison.OrdinalIgnoreCase));
                    Element te;
                    if (existing == null) te = w.CreateTable(target, "", t);
                    else
                    {
                        te = existing;
                        w.UpdateTable(te, t);
                        foreach (var c in t.Columns)
                            if (DbModel.Column(te, c.Name) is { } col) w.UpdateColumn(col, c, t.IsPrimaryKey(c.Name));
                            else w.CreateColumn(te, "", t, c);
                        w.SetPrimaryKey(te, t);
                    }
                    tables[DbPaths.Table(s.Name, t.Name)] = te;
                }
            var fks = 0;
            foreach (var s in catalog.Schemas)
                foreach (var t in s.Tables)
                    foreach (var fk in t.ForeignKeys)
                    {
                        var to = DbImport.ResolveTable(catalog, tables, s.Name, fk);
                        if (to == null) continue;
                        var r = m.Connect(ElementKind.ForeignKey, tables[DbPaths.Table(s.Name, t.Name)], to, target);
                        w.UpdateForeignKey(r, fk);
                        fks++;
                    }
            if (diagram != null)
            {
                var i = 0;
                foreach (var t in tables.Values)
                {
                    var h = 46 + Math.Max(1, DbModel.Columns(t).Count()) * 16;
                    m.AddNode(diagram, t, new Bounds(40 + (i % 4) * 260, 40 + (i / 4) * 260, 220, h));
                    i++;
                }
            }
            return (tables.Count, fks);
        }
    }
}
