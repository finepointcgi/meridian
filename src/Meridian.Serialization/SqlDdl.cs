using System.Text;
using System.Text.RegularExpressions;
using Meridian.Core.Model;

namespace Meridian.Serialization;

public enum SqlDialect { PostgreSql, MySql, SqlServer, Sqlite }

/// <summary>Data modeling: DDL generation from tables/columns/foreign keys, and reverse engineering from CREATE TABLE scripts.</summary>
public static partial class SqlDdl
{
    private static string Q(string name, SqlDialect d) => d switch
    {
        SqlDialect.MySql => $"`{name}`",
        SqlDialect.SqlServer => $"[{name}]",
        _ => $"\"{name}\"",
    };

    public static string Generate(ModelRepository m, SqlDialect dialect)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"-- Generated by Meridian from '{m.Root.Name}' ({dialect})");
        var tables = m.OfKind(ElementKind.Table).OrderBy(t => t.Name).ToList();
        foreach (var t in tables)
        {
            sb.AppendLine($"CREATE TABLE {Q(t.Name, dialect)} (");
            var lines = new List<string>();
            var cols = t.OwnedElements.Where(c => c.Kind == ElementKind.Column).ToList();
            foreach (var c in cols)
            {
                var type = c.Get(FieldKeys.SqlType) is { Length: > 0 } st ? st : "text";
                var line = $"    {Q(c.Name, dialect)} {type}";
                if (c.Get(FieldKeys.Nullable) != "true" || c.Get(FieldKeys.PrimaryKey) == "true") line += " NOT NULL";
                if (c.Get(FieldKeys.Unique) == "true") line += " UNIQUE";
                if (c.Get(FieldKeys.DefaultValue) is { Length: > 0 } dv) line += $" DEFAULT {dv}";
                lines.Add(line);
            }
            var pk = cols.Where(c => c.Get(FieldKeys.PrimaryKey) == "true").Select(c => Q(c.Name, dialect)).ToList();
            if (pk.Count > 0) lines.Add($"    PRIMARY KEY ({string.Join(", ", pk)})");
            if (dialect == SqlDialect.Sqlite)
                foreach (var fk in m.Outgoing(t, ElementKind.ForeignKey)) lines.Add("    " + FkClause(fk, dialect));
            sb.AppendLine(string.Join(",\n", lines));
            sb.AppendLine(");");
            if (!string.IsNullOrWhiteSpace(t.Documentation) && dialect == SqlDialect.PostgreSql)
                sb.AppendLine($"COMMENT ON TABLE {Q(t.Name, dialect)} IS '{t.Documentation.Replace("'", "''")}';");
            sb.AppendLine();
        }
        if (dialect != SqlDialect.Sqlite)
            foreach (var fk in tables.SelectMany(t => m.Outgoing(t, ElementKind.ForeignKey)))
                sb.AppendLine($"ALTER TABLE {Q(fk.Source.Name, dialect)} ADD {(string.IsNullOrEmpty(fk.Name) ? "" : $"CONSTRAINT {Q(fk.Name, dialect)} ")}{FkClause(fk, dialect)};");
        return sb.ToString();
    }

    private static string FkClause(Relationship fk, SqlDialect d)
    {
        var cols = Split(fk.Get(FieldKeys.FkColumns));
        var refs = Split(fk.Get(FieldKeys.RefColumns));
        if (cols.Count == 0) cols = [fk.Target.Name.ToLowerInvariant() + "_id"];
        if (refs.Count == 0)
            refs = fk.Target.OwnedElements.Where(c => c.Get(FieldKeys.PrimaryKey) == "true").Select(c => c.Name).DefaultIfEmpty("id").ToList();
        return $"FOREIGN KEY ({string.Join(", ", cols.Select(c => Q(c, d)))}) REFERENCES {Q(fk.Target.Name, d)} ({string.Join(", ", refs.Select(c => Q(c, d)))})";
    }

    private static List<string> Split(string s) => s.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).ToList();

    [GeneratedRegex(@"create\s+table\s+(?:if\s+not\s+exists\s+)?([\w\.""`\[\]]+)\s*\((.*?)\)\s*;", RegexOptions.IgnoreCase | RegexOptions.Singleline)]
    private static partial Regex CreateTableRegex();

    [GeneratedRegex(@"alter\s+table\s+([\w\.""`\[\]]+)\s+add\s+(?:constraint\s+([\w""`\[\]]+)\s+)?foreign\s+key\s*\(([^)]*)\)\s*references\s+([\w\.""`\[\]]+)\s*\(([^)]*)\)", RegexOptions.IgnoreCase)]
    private static partial Regex AlterFkRegex();

    private static string Unquote(string s)
    {
        s = s.Trim().Trim('"', '`', '[', ']');
        var dot = s.LastIndexOf('.');
        return (dot >= 0 ? s[(dot + 1)..] : s).Trim('"', '`', '[', ']');
    }

    /// <summary>Splits a column list on commas that are not inside parentheses (e.g. numeric(10,2)).</summary>
    private static IEnumerable<string> SplitTopLevel(string body)
    {
        var depth = 0; var start = 0;
        for (var i = 0; i < body.Length; i++)
        {
            if (body[i] == '(') depth++;
            else if (body[i] == ')') depth--;
            else if (body[i] == ',' && depth == 0) { yield return body[start..i]; start = i + 1; }
        }
        yield return body[start..];
    }

    /// <summary>Reverse-engineers CREATE TABLE / ALTER TABLE … FOREIGN KEY into tables, columns and foreign keys.</summary>
    public static (int Tables, int ForeignKeys) Import(ModelRepository m, Element target, string ddl, Diagram? diagram = null)
    {
        ddl = Regex.Replace(ddl, @"--[^\n]*", "");
        ddl = Regex.Replace(ddl, @"/\*.*?\*/", "", RegexOptions.Singleline);
        var tables = new Dictionary<string, Element>(StringComparer.OrdinalIgnoreCase);
        var fks = new List<(Element Table, string? Name, string Cols, string RefTable, string RefCols)>();
        using (m.History.Transaction("Import DDL"))
        {
            foreach (Match tm in CreateTableRegex().Matches(ddl))
            {
                var name = Unquote(tm.Groups[1].Value);
                var table = m.OfKind(ElementKind.Table).FirstOrDefault(t => t.Name.Equals(name, StringComparison.OrdinalIgnoreCase)) ?? m.Create(target, ElementKind.Table, name);
                tables[name] = table;
                var pkCols = new List<string>();
                foreach (var raw in SplitTopLevel(tm.Groups[2].Value).Select(p => p.Trim()).Where(p => p.Length > 0))
                {
                    var lower = raw.ToLowerInvariant();
                    var pk = Regex.Match(raw, @"^(?:constraint\s+\S+\s+)?primary\s+key\s*\(([^)]*)\)", RegexOptions.IgnoreCase);
                    if (pk.Success) { pkCols.AddRange(pk.Groups[1].Value.Split(',').Select(Unquote)); continue; }
                    var fk = Regex.Match(raw, @"^(?:constraint\s+(\S+)\s+)?foreign\s+key\s*\(([^)]*)\)\s*references\s+([\w\.""`\[\]]+)\s*\(([^)]*)\)", RegexOptions.IgnoreCase);
                    if (fk.Success) { fks.Add((table, fk.Groups[1].Success ? Unquote(fk.Groups[1].Value) : null, fk.Groups[2].Value, fk.Groups[3].Value, fk.Groups[4].Value)); continue; }
                    if (lower.StartsWith("unique") || lower.StartsWith("check") || lower.StartsWith("constraint") || lower.StartsWith("index") || lower.StartsWith("key ")) continue;
                    var parts = Regex.Match(raw, @"^([\w""`\[\]]+)\s+(.+)$", RegexOptions.Singleline);
                    if (!parts.Success) continue;
                    var colName = Unquote(parts.Groups[1].Value);
                    var rest = parts.Groups[2].Value;
                    var typeMatch = Regex.Match(rest, @"^([\w\s]+?(?:\([^)]*\))?)(?=\s+(?:not|null|primary|unique|default|references|check|constraint|generated|auto_increment|identity)\b|$)", RegexOptions.IgnoreCase);
                    var type = typeMatch.Success ? typeMatch.Groups[1].Value.Trim() : rest.Split(' ')[0];
                    var col = table.OwnedElements.FirstOrDefault(c => c.Name.Equals(colName, StringComparison.OrdinalIgnoreCase)) ?? m.Create(table, ElementKind.Column, colName);
                    m.Set(col, FieldKeys.SqlType, type);
                    var restLower = rest.ToLowerInvariant();
                    if (restLower.Contains("primary key")) pkCols.Add(colName);
                    m.Set(col, FieldKeys.Nullable, restLower.Contains("not null") || restLower.Contains("primary key") ? null : "true");
                    if (restLower.Contains("unique")) m.Set(col, FieldKeys.Unique, "true");
                    var dv = Regex.Match(rest, @"default\s+('[^']*'|\S+)", RegexOptions.IgnoreCase);
                    if (dv.Success) m.Set(col, FieldKeys.DefaultValue, dv.Groups[1].Value);
                    var inlineRef = Regex.Match(rest, @"references\s+([\w\.""`\[\]]+)\s*(?:\(([^)]*)\))?", RegexOptions.IgnoreCase);
                    if (inlineRef.Success) fks.Add((table, null, colName, inlineRef.Groups[1].Value, inlineRef.Groups[2].Success ? inlineRef.Groups[2].Value : ""));
                }
                foreach (var c in table.OwnedElements.Where(c => c.Kind == ElementKind.Column && pkCols.Contains(c.Name, StringComparer.OrdinalIgnoreCase)))
                    m.Set(c, FieldKeys.PrimaryKey, "true");
            }
            foreach (Match am in AlterFkRegex().Matches(ddl))
                if (tables.TryGetValue(Unquote(am.Groups[1].Value), out var t))
                    fks.Add((t, am.Groups[2].Success ? Unquote(am.Groups[2].Value) : null, am.Groups[3].Value, am.Groups[4].Value, am.Groups[5].Value));

            var fkCount = 0;
            foreach (var (table, name, cols, refTable, refCols) in fks)
            {
                if (!tables.TryGetValue(Unquote(refTable), out var target2)) continue;
                var r = m.Connect(ElementKind.ForeignKey, table, target2, target);
                m.Set(r, FieldKeys.Name, name);
                m.Set(r, FieldKeys.FkColumns, string.Join(", ", cols.Split(',').Select(Unquote)));
                m.Set(r, FieldKeys.RefColumns, string.Join(", ", refCols.Split(',', StringSplitOptions.RemoveEmptyEntries).Select(Unquote)));
                fkCount++;
            }
            if (diagram != null)
            {
                var i = 0;
                foreach (var t in tables.Values)
                {
                    var h = 46 + Math.Max(1, t.OwnedElements.Count(c => c.Kind == ElementKind.Column)) * 16;
                    m.AddNode(diagram, t, new Bounds(40 + (i % 4) * 260, 40 + (i / 4) * 260, 220, h));
                    i++;
                }
            }
            return (tables.Count, fkCount);
        }
    }
}
