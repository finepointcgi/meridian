using System.Text;
using Meridian.Core.Language;
using Meridian.Core.Model;

namespace Meridian.Serialization;

/// <summary>Options for <see cref="SysMLv2Text.Export(ModelRepository, SysMLv2ExportOptions)"/>.</summary>
public sealed record SysMLv2ExportOptions
{
    /// <summary>The package (or model) to export; null exports the whole model.</summary>
    public Element? Scope { get; init; }

    /// <summary>Writes a <c>/* @id _… */</c> comment in every declaration so edited text maps back to the same elements
    /// (renames and moves keep identity, diagrams and relationships).</summary>
    public bool EmitIds { get; init; }
}

/// <summary>
/// SysML v2 textual notation (.sysml): export of the model (or one package) and import through
/// <see cref="SysMLv2Parser"/> + <see cref="SysMLv2Sync"/>.
/// </summary>
public static class SysMLv2Text
{
    /// <summary>Field holding a transition's trigger (<c>accept X</c>).</summary>
    public const string TriggerField = "trigger";

    /// <summary>Field holding a requirement's subject declaration (<c>subject v : Vehicle</c>).</summary>
    public const string SubjectField = "subject";

    // ======================================================================= export

    public static string Export(ModelRepository model) => Export(model, new SysMLv2ExportOptions());

    public static string Export(ModelRepository model, SysMLv2ExportOptions options)
    {
        var w = new Writer(model, options);
        w.Sb.AppendLine("// Generated by Meridian — SysML v2 textual notation");
        var scope = options.Scope is { } s && model.Contains(s) ? s : model.Root;
        if (scope.Kind is ElementKind.Package or ElementKind.Model) w.WritePackage(scope, 0);
        else w.WriteMember(scope, 0);
        return w.Sb.ToString();
    }

    private sealed class Writer(ModelRepository m, SysMLv2ExportOptions o)
    {
        public readonly StringBuilder Sb = new();
        private readonly SysmlNameIndex _names = new(m);

        private string Id(Element e) => o.EmitIds ? $" /* @id {e.Id} */" : "";

        private string Ref(Element target, Element context, Func<Element, bool>? filter = null) => _names.RefText(target, context, filter);

        public void WritePackage(Element pkg, int depth)
        {
            Line(depth, $"package {N(pkg.Name)}{Id(pkg)} {{");
            Doc(depth + 1, pkg.Documentation);
            foreach (var c in pkg.OwnedElements) WriteMember(c, depth + 1);
            // Cross-cutting relationships of this namespace
            foreach (var r in pkg.OwnedElements.OfType<Relationship>()) WriteRelationship(r, pkg, depth + 1);
            Line(depth, "}");
        }

        /// <summary>Writes "header;" or "header { doc }" for leaf declarations that may carry documentation.</summary>
        private void Leaf(int d, string header, Element e)
        {
            if (string.IsNullOrWhiteSpace(e.Documentation)) { Line(d, header + Id(e) + ";"); return; }
            Line(d, header + Id(e) + " {");
            Doc(d + 1, e.Documentation);
            Line(d, "}");
        }

        public void WriteMember(Element e, int d)
        {
            if (e is Relationship or Diagram) return;
            switch (e.Kind)
            {
                case ElementKind.Package: WritePackage(e, d); return;
                case ElementKind.Comment: Line(d, $"comment /* {Esc(e.Get(FieldKeys.Body))} */"); return;
                case ElementKind.Property:
                {
                    var t = m.ResolveType(e);
                    var kw = t?.Kind is ElementKind.Block or ElementKind.Class or ElementKind.Component ? "part"
                           : t?.Kind is ElementKind.InterfaceBlock ? "port"
                           : "attribute";
                    Leaf(d, $"{kw} {N(e.Name)}{TypeSuffix(e)}{Mult(e)}{Default(e)}", e);
                    return;
                }
                case ElementKind.Port:
                {
                    var dir = e.Get(FieldKeys.Direction) is { Length: > 0 } dd ? dd + " " : "";
                    Leaf(d, $"{dir}port {N(e.Name)}{TypeSuffix(e)}{Mult(e)}", e);
                    return;
                }
                case ElementKind.Operation:
                    Line(d, $"// operation {e.Name}{e.Get(FieldKeys.Signature)}");
                    return;
                case ElementKind.Lifeline:
                    Leaf(d, $"part {N(e.Name)}{TypeSuffix(e)}", e);
                    return;
                case ElementKind.CombinedFragment:
                    Line(d, $"// {e.Get(FieldKeys.Operator)}{(e.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" [{g}]" : "")}");
                    return;
                case ElementKind.EnumerationLiteral:
                    Leaf(d, $"enum {N(e.Name)}", e);
                    return;
                case ElementKind.Action:
                {
                    var behavior = m.Find(e.Get(FieldKeys.Behavior)) is { Kind: ElementKind.Activity } b ? " : " + Ref(b, e.Owner!, x => x.Kind == ElementKind.Activity) : "";
                    Leaf(d, $"action {N(e.Name)}{behavior}", e);
                    return;
                }
                case ElementKind.State:
                    if (e.OwnedElements.Count == 0 && string.IsNullOrWhiteSpace(e.Documentation)) { Line(d, $"state {N(e.Name)}{Id(e)};"); return; }
                    Line(d, $"state {N(e.Name)}{Id(e)} {{");
                    Doc(d + 1, e.Documentation);
                    WriteBehaviorBody(e, d + 1);
                    Line(d, "}");
                    return;
                case ElementKind.InitialNode or ElementKind.InitialState or ElementKind.ActivityFinalNode or ElementKind.FinalState
                    or ElementKind.DecisionNode or ElementKind.ForkNode:
                    var kw2 = e.Kind switch { ElementKind.DecisionNode => "decide", ElementKind.ForkNode => "fork", _ => null };
                    if (kw2 != null) Line(d, $"{kw2} {N(SysmlNameIndex.ExportName(e))}{Id(e)};");
                    return;
            }

            var keyword = Keyword(e.Kind);
            if (keyword == null) return;

            var header = new StringBuilder();
            if (e.IsAbstract) header.Append("abstract ");
            if (e.Kind == ElementKind.Actor) header.Append("#actor ");
            header.Append(keyword).Append(' ');
            if (e.Kind == ElementKind.Requirement && e.Get(FieldKeys.RequirementId) is { Length: > 0 } rid) header.Append($"<'{Q(rid)}'> ");
            header.Append(N(e.Name));
            var supers = m.General(e).Select(g => Ref(g, e.Owner ?? m.Root, x => Metamodel.IsClassifier(x.Kind))).ToList();
            if (supers.Count > 0) header.Append(" :> ").Append(string.Join(", ", supers));
            header.Append(Id(e));

            var hasBody = e.OwnedElements.Any(c => c is not Diagram) || !string.IsNullOrWhiteSpace(e.Documentation) ||
                          e.Kind == ElementKind.Requirement || (e.Kind == ElementKind.ConstraintBlock && e.Get(FieldKeys.Body).Length > 0) ||
                          (e.Kind == ElementKind.TestCase && m.Outgoing(e, ElementKind.Verify).Any()) ||
                          m.Outgoing(e).Any(r => r.Kind is ElementKind.Include or ElementKind.Extend);
            if (!hasBody) { Line(d, header + ";"); return; }

            Line(d, header + " {");
            Doc(d + 1, e.Kind == ElementKind.Requirement ? e.Get(FieldKeys.Text) : e.Documentation);
            if (e.Kind == ElementKind.Requirement && !string.IsNullOrWhiteSpace(e.Documentation)) Line(d + 1, $"comment /* {Esc(e.Documentation)} */");
            if (e.Kind == ElementKind.Requirement && e.Get(SubjectField) is { Length: > 0 } subject) Line(d + 1, $"subject {subject};");
            if (e.Kind == ElementKind.TestCase)
                foreach (var v in m.Outgoing(e, ElementKind.Verify))
                    Line(d + 1, $"objective {{ verify {Ref(v.Target, e)}; }}");
            foreach (var inc in m.Outgoing(e).Where(r => r.Kind is ElementKind.Include or ElementKind.Extend))
                Line(d + 1, inc.Kind == ElementKind.Include ? $"include use case {Ref(inc.Target, e)};" : $"#extend dependency from {Ref(e, e)} to {Ref(inc.Target, e)};");
            if (e.Kind is ElementKind.Activity or ElementKind.StateMachine) WriteBehaviorBody(e, d + 1);
            else foreach (var c in e.OwnedElements) WriteMember(c, d + 1);
            foreach (var r in e.OwnedElements.OfType<Relationship>().Where(r => r.Kind != ElementKind.Verify)) WriteRelationship(r, e, d + 1);
            // A constraint's expression comes last, as SysML v2 requires.
            if (e.Kind == ElementKind.ConstraintBlock && e.Get(FieldKeys.Body) is { Length: > 0 } body)
                foreach (var l in body.Replace("\r", "").Split('\n')) Line(d + 1, l.Trim());
            Line(d, "}");
        }

        private void WriteBehaviorBody(Element owner, int d)
        {
            foreach (var c in owner.OwnedElements.Where(c => c is not Relationship)) WriteMember(c, d);
            foreach (var r in owner.OwnedElements.OfType<Relationship>())
            {
                if (r.Kind == ElementKind.Transition)
                {
                    var from = NodeRef(r.Source, owner);
                    var to = NodeRef(r.Target, owner);
                    var trigger = r.Get(TriggerField) is { Length: > 0 } tr ? $" accept {tr}" : "";
                    var guard = r.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" if {g}" : "";
                    var effect = r.Get(FieldKeys.Effect) is { Length: > 0 } fx ? $" do {fx}" : "";
                    var name = string.IsNullOrEmpty(r.Name) ? "" : N(r.Name) + " ";
                    Line(d, $"transition {name}first {from}{trigger}{guard}{effect} then {to};");
                }
                else if (r.Kind is ElementKind.ControlFlow or ElementKind.ObjectFlow)
                {
                    var guard = r.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" if {g}" : "";
                    Line(d, $"first {NodeRef(r.Source, owner)}{guard} then {NodeRef(r.Target, owner)};");
                }
            }
        }

        private string NodeRef(Element e, Element owner)
        {
            if (e.Kind is ElementKind.InitialNode or ElementKind.InitialState) return "start";
            if (e.Kind is ElementKind.ActivityFinalNode or ElementKind.FinalState) return "done";
            var name = SysmlNameIndex.ExportName(e);
            return ReferenceEquals(SysMLv2Sync.FindNode(owner, name), e) ? N(name) : Ref(e, owner);
        }

        private string End(Element e, string partId, Element context) =>
            m.Find(partId) is { } part && !ReferenceEquals(part, e) ? $"{N(part.Name)}.{N(e.Name)}" : Ref(e, context);

        private void WriteRelationship(Relationship r, Element context, int d)
        {
            string S() => Ref(r.Source, context);
            string T() => Ref(r.Target, context);
            switch (r.Kind)
            {
                case ElementKind.Satisfy: Line(d, $"satisfy {T()} by {S()};"); break;
                case ElementKind.Allocate: Line(d, $"allocate {S()} to {T()};"); break;
                case ElementKind.Dependency: Line(d, $"dependency from {S()} to {T()};"); break;
                case ElementKind.DeriveReqt: Line(d, $"#derivation dependency from {S()} to {T()};"); break;
                case ElementKind.Refine: Line(d, $"#refinement dependency from {S()} to {T()};"); break;
                case ElementKind.Trace: Line(d, $"#trace dependency from {S()} to {T()};"); break;
                case ElementKind.Verify: Line(d, $"// {S()} verifies {T()}"); break;
                case ElementKind.Message:
                {
                    var tag = r.Get(FieldKeys.MessageSort) switch { "reply" => "#reply ", "asynchCall" => "#async ", _ => "" };
                    var name = string.IsNullOrEmpty(r.Name) ? "" : N(r.Name) + " ";
                    Line(d, $"{tag}message {name}from {S()} to {T()};");
                    break;
                }
                case ElementKind.Connector:
                {
                    var a = End(r.Source, r.Get(FieldKeys.SourcePart), context);
                    var b = End(r.Target, r.Get(FieldKeys.TargetPart), context);
                    if (r.Get(FieldKeys.ItemFlow) is { Length: > 0 } item)
                    {
                        var itemText = m.Find(item) is { } ie ? Ref(ie, context) : QName(item);
                        Line(d, $"flow {(string.IsNullOrEmpty(r.Name) ? "" : N(r.Name) + " ")}of {itemText} from {a} to {b};");
                    }
                    else if (!string.IsNullOrEmpty(r.Name)) Line(d, $"connection {N(r.Name)} connect {a} to {b};");
                    else Line(d, $"connect {a} to {b};");
                    break;
                }
                case ElementKind.Binding:
                    Line(d, $"bind {End(r.Source, r.Get(FieldKeys.SourcePart), context)} = {End(r.Target, r.Get(FieldKeys.TargetPart), context)};");
                    break;
                case ElementKind.Composition or ElementKind.Aggregation or ElementKind.Association:
                    // Represented as a usage inside the source definition in v2; emitted as a comment here.
                    Line(d, $"// {r.Kind}: {S()} -> {T()} [{r.Multiplicity}]"); break;
            }
        }

        private string TypeSuffix(Element e)
        {
            if (m.ResolveType(e) is { } t) return " : " + Ref(t, e.Owner ?? m.Root, x => Metamodel.IsClassifier(x.Kind));
            var raw = e.TypeRef;
            if (string.IsNullOrEmpty(raw)) return "";
            return " : " + (Metamodel.PrimitiveTypes.Contains(raw) ? "ScalarValues::" + raw : QName(raw));
        }

        private static string Mult(Element e) => string.IsNullOrEmpty(e.Multiplicity) || e.Multiplicity == "1" ? "" : $"[{e.Multiplicity}]";
        private static string Default(Element e) => e.Get(FieldKeys.DefaultValue) is { Length: > 0 } v ? $" = {v}" : "";

        private void Doc(int d, string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return;
            Line(d, $"doc /* {Esc(text)} */");
        }

        private void Line(int depth, string s) => Sb.Append(' ', depth * 4).AppendLine(s);
    }

    internal static string? Keyword(ElementKind k) => k switch
    {
        ElementKind.Block or ElementKind.Class or ElementKind.Component or ElementKind.Actor => "part def",
        ElementKind.InterfaceBlock or ElementKind.Interface => "port def",
        ElementKind.ValueType or ElementKind.DataType => "attribute def",
        ElementKind.Enumeration => "enum def",
        ElementKind.ConstraintBlock => "constraint def",
        ElementKind.Requirement => "requirement def",
        ElementKind.TestCase => "verification def",
        ElementKind.UseCase => "use case def",
        ElementKind.Activity => "action def",
        ElementKind.StateMachine => "state def",
        ElementKind.Interaction => "occurrence def",
        _ => null,
    };

    private static string Esc(string text) => text.Replace("*/", "* /");

    /// <summary>Quotes a name if it isn't a plain identifier.</summary>
    public static string N(string name)
    {
        if (string.IsNullOrEmpty(name)) return "'unnamed'";
        var plain = (char.IsLetter(name[0]) || name[0] == '_') && name.All(c => char.IsLetterOrDigit(c) || c == '_') && !Keywords.Contains(name);
        return plain ? name : $"'{Q(name)}'";
    }

    /// <summary>Writes a possibly qualified name (A::B) with each segment quoted as needed.</summary>
    private static string QName(string name) =>
        name.Contains("::") ? string.Join("::", name.Split("::").Select(N)) : N(name);

    private static string Q(string s) => s.Replace("\\", "\\\\").Replace("'", "\\'");

    private static readonly HashSet<string> Keywords = new(SysMLv2Parser.StatementKeywords)
    {
        "def", "by", "to", "from", "of", "start", "done", "about", "specializes", "subsets", "redefines", "references", "defined", "typed",
        "not", "and", "or", "xor", "true", "false", "null", "all", "default", "ordered", "nonunique", "via", "do", "parallel", "locale",
    };

    // ======================================================================= import

    /// <summary>Parses SysML v2 text into a new model. A single top-level package becomes the model itself.
    /// Problems are reported as warnings; whatever could be understood is imported.</summary>
    public static (ModelRepository Model, ImportReport Report) Import(string text, string modelName = "Imported")
    {
        var doc = SysMLv2Parser.Parse(text);
        var model = new ModelRepository(modelName);
        var result = SysMLv2Sync.Apply(model, model.Root, doc, new SysmlSyncOptions { AllowErrors = true, Description = "Import SysML v2" });
        model.History.Clear();
        var warnings = doc.Diagnostics.Concat(result.Diagnostics).Where(d => d.Severity != SysmlSeverity.Info).Select(d => d.ToString()).ToList();
        return (model, new ImportReport(result.ElementsCreated, result.RelationshipsCreated, warnings));
    }
}
