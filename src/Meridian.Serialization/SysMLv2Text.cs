using System.Text;
using Meridian.Core.Language;
using Meridian.Core.Model;

namespace Meridian.Serialization;

/// <summary>
/// SysML v2 textual notation (.sysml): export of the whole model and import of a practical subset
/// (packages, part/port/attribute/item/enum/constraint/requirement/action/state/use case defs and usages,
/// specialization, doc, satisfy/verify/allocate/dependency, successions and transitions).
/// </summary>
public static class SysMLv2Text
{
    // ======================================================================= export

    public static string Export(ModelRepository model)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"// Generated by Meridian — SysML v2 textual notation");
        WritePackage(model, model.Root, sb, 0);
        return sb.ToString();
    }

    private static void WritePackage(ModelRepository m, Element pkg, StringBuilder sb, int depth)
    {
        Line(sb, depth, $"package {N(pkg.Name)} {{");
        Doc(sb, depth + 1, pkg.Documentation);
        foreach (var c in pkg.OwnedElements) WriteMember(m, c, sb, depth + 1);
        // Cross-cutting relationships of this namespace
        foreach (var r in pkg.OwnedElements.OfType<Relationship>()) WriteRelationship(r, sb, depth + 1);
        Line(sb, depth, "}");
    }

    private static void WriteMember(ModelRepository m, Element e, StringBuilder sb, int d)
    {
        if (e is Relationship or Diagram) return;
        switch (e.Kind)
        {
            case ElementKind.Package: WritePackage(m, e, sb, d); return;
            case ElementKind.Comment: Line(sb, d, $"comment /* {e.Get(FieldKeys.Body)} */"); return;
            case ElementKind.Property:
            {
                var t = m.ResolveType(e);
                var kw = t?.Kind is ElementKind.Block or ElementKind.Class or ElementKind.Component ? "part"
                       : t?.Kind is ElementKind.InterfaceBlock ? "port"
                       : "attribute";
                Line(sb, d, $"{kw} {N(e.Name)}{TypeSuffix(m, e)}{Mult(e)}{Default(e)};" + DocInline(e));
                return;
            }
            case ElementKind.Port:
            {
                var dir = e.Get(FieldKeys.Direction) is { Length: > 0 } dd ? dd + " " : "";
                Line(sb, d, $"{dir}port {N(e.Name)}{TypeSuffix(m, e)}{Mult(e)};" + DocInline(e));
                return;
            }
            case ElementKind.Operation:
                Line(sb, d, $"// operation {e.Name}{e.Get(FieldKeys.Signature)}");
                return;
            case ElementKind.Lifeline:
                Line(sb, d, $"part {N(e.Name)}{TypeSuffix(m, e)};");
                return;
            case ElementKind.CombinedFragment:
                Line(sb, d, $"// {e.Get(FieldKeys.Operator)}{(e.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" [{g}]" : "")}");
                return;
            case ElementKind.EnumerationLiteral:
                Line(sb, d, $"enum {N(e.Name)};");
                return;
            case ElementKind.Action:
                Line(sb, d, $"action {N(e.Name)};" + DocInline(e));
                return;
            case ElementKind.State:
                if (e.OwnedElements.Count == 0) { Line(sb, d, $"state {N(e.Name)};"); return; }
                Line(sb, d, $"state {N(e.Name)} {{");
                WriteBehaviorBody(m, e, sb, d + 1);
                Line(sb, d, "}");
                return;
            case ElementKind.InitialNode or ElementKind.InitialState or ElementKind.ActivityFinalNode or ElementKind.FinalState
                or ElementKind.DecisionNode or ElementKind.ForkNode:
                var kw2 = e.Kind switch { ElementKind.DecisionNode => "decide", ElementKind.ForkNode => "fork", _ => null };
                if (kw2 != null) Line(sb, d, $"{kw2} {N(NodeName(e))};");
                return;
        }

        var (keyword, isDef) = e.Kind switch
        {
            ElementKind.Block or ElementKind.Class or ElementKind.Component or ElementKind.Actor => ("part def", true),
            ElementKind.InterfaceBlock or ElementKind.Interface => ("port def", true),
            ElementKind.ValueType or ElementKind.DataType => ("attribute def", true),
            ElementKind.Enumeration => ("enum def", true),
            ElementKind.ConstraintBlock => ("constraint def", true),
            ElementKind.Requirement => ("requirement def", true),
            ElementKind.TestCase => ("verification def", true),
            ElementKind.UseCase => ("use case def", true),
            ElementKind.Activity => ("action def", true),
            ElementKind.StateMachine => ("state def", true),
            ElementKind.Interaction => ("occurrence def", true),
            _ => ((string?)null, false),
        };
        if (keyword == null) return;

        var header = new StringBuilder();
        if (e.IsAbstract) header.Append("abstract ");
        if (e.Kind == ElementKind.Actor) header.Append("#actor ");
        header.Append(keyword).Append(' ');
        if (e.Kind == ElementKind.Requirement && e.Get(FieldKeys.RequirementId) is { Length: > 0 } rid) header.Append($"<'{Q(rid)}'> ");
        header.Append(N(e.Name));
        var supers = m.General(e).Select(g => N(g.Name)).ToList();
        if (supers.Count > 0) header.Append(" :> ").Append(string.Join(", ", supers));

        var hasBody = e.OwnedElements.Any(c => c is not Diagram) || !string.IsNullOrWhiteSpace(e.Documentation) ||
                      e.Kind == ElementKind.Requirement || (e.Kind == ElementKind.ConstraintBlock && e.Get(FieldKeys.Body).Length > 0) ||
                      (e.Kind == ElementKind.TestCase && m.Outgoing(e, ElementKind.Verify).Any()) ||
                      m.Outgoing(e).Any(r => r.Kind is ElementKind.Include or ElementKind.Extend);
        if (!hasBody) { Line(sb, d, header + ";"); return; }

        Line(sb, d, header + " {");
        Doc(sb, d + 1, e.Kind == ElementKind.Requirement ? e.Get(FieldKeys.Text) : e.Documentation);
        if (e.Kind == ElementKind.Requirement && !string.IsNullOrWhiteSpace(e.Documentation)) Line(sb, d + 1, $"comment /* {e.Documentation} */");
        if (e.Kind == ElementKind.ConstraintBlock && e.Get(FieldKeys.Body) is { Length: > 0 } body) Line(sb, d + 1, $"{body}");
        if (e.Kind == ElementKind.TestCase)
            foreach (var v in m.Outgoing(e, ElementKind.Verify))
                Line(sb, d + 1, $"objective {{ verify {N(v.Target.Name)}; }}");
        foreach (var inc in m.Outgoing(e).Where(r => r.Kind is ElementKind.Include or ElementKind.Extend))
            Line(sb, d + 1, inc.Kind == ElementKind.Include ? $"include use case {N(inc.Target.Name)};" : $"#extend dependency from {N(e.Name)} to {N(inc.Target.Name)};");
        if (e.Kind is ElementKind.Activity or ElementKind.StateMachine) WriteBehaviorBody(m, e, sb, d + 1);
        else foreach (var c in e.OwnedElements) WriteMember(m, c, sb, d + 1);
        foreach (var r in e.OwnedElements.OfType<Relationship>().Where(r => r.Kind != ElementKind.Verify)) WriteRelationship(r, sb, d + 1);
        Line(sb, d, "}");
    }

    private static void WriteBehaviorBody(ModelRepository m, Element owner, StringBuilder sb, int d)
    {
        foreach (var c in owner.OwnedElements.Where(c => c is not Relationship)) WriteMember(m, c, sb, d);
        foreach (var r in owner.OwnedElements.OfType<Relationship>())
        {
            var from = NodeName(r.Source);
            var to = NodeName(r.Target);
            if (r.Kind == ElementKind.Transition)
            {
                var guard = r.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" if {g}" : "";
                var effect = r.Get(FieldKeys.Effect) is { Length: > 0 } fx ? $" do {fx}" : "";
                var name = string.IsNullOrEmpty(r.Name) ? "" : N(r.Name) + " ";
                Line(sb, d, $"transition {name}first {from}{guard}{effect} then {to};");
            }
            else if (r.Kind is ElementKind.ControlFlow or ElementKind.ObjectFlow)
            {
                var guard = r.Get(FieldKeys.Guard) is { Length: > 0 } g ? $" if {g}" : "";
                Line(sb, d, $"first {from}{guard} then {to};");
            }
        }
    }

    private static string NodeName(Element e) => e.Kind switch
    {
        ElementKind.InitialNode or ElementKind.InitialState => "start",
        ElementKind.ActivityFinalNode or ElementKind.FinalState => "done",
        _ => string.IsNullOrEmpty(e.Name) ? (e.Kind == ElementKind.DecisionNode ? "decision" : "fork") + (e.Owner?.OwnedElements.Where(c => c.Kind == e.Kind).ToList().IndexOf(e) + 1) : N(e.Name),
    };

    private static void WriteRelationship(Relationship r, StringBuilder sb, int d)
    {
        var s = N(r.Source.Name); var t = N(r.Target.Name);
        switch (r.Kind)
        {
            case ElementKind.Satisfy: Line(sb, d, $"satisfy {t} by {s};"); break;
            case ElementKind.Allocate: Line(sb, d, $"allocate {s} to {t};"); break;
            case ElementKind.Dependency: Line(sb, d, $"dependency from {s} to {t};"); break;
            case ElementKind.DeriveReqt: Line(sb, d, $"#derivation dependency from {s} to {t};"); break;
            case ElementKind.Refine: Line(sb, d, $"#refinement dependency from {s} to {t};"); break;
            case ElementKind.Trace: Line(sb, d, $"#trace dependency from {s} to {t};"); break;
            case ElementKind.Verify: Line(sb, d, $"// {s} verifies {t}"); break;
            case ElementKind.Message:
            {
                var tag = r.Get(FieldKeys.MessageSort) switch { "reply" => "#reply ", "asynchCall" => "#async ", _ => "" };
                var name = string.IsNullOrEmpty(r.Name) ? "" : N(r.Name) + " ";
                Line(sb, d, $"{tag}message {name}from {s} to {t};");
                break;
            }
            case ElementKind.Composition or ElementKind.Aggregation or ElementKind.Association:
                // Represented as a usage inside the source definition in v2; emitted as a comment here.
                Line(sb, d, $"// {r.Kind}: {s} -> {t} [{r.Multiplicity}]"); break;
        }
    }

    private static string TypeSuffix(ModelRepository m, Element e)
    {
        var t = m.TypeDisplayName(e);
        if (string.IsNullOrEmpty(t)) return "";
        return " : " + (Metamodel.PrimitiveTypes.Contains(t) ? "ScalarValues::" + t : N(t));
    }

    private static string Mult(Element e) => string.IsNullOrEmpty(e.Multiplicity) || e.Multiplicity == "1" ? "" : $"[{e.Multiplicity}]";
    private static string Default(Element e) => e.Get(FieldKeys.DefaultValue) is { Length: > 0 } v ? $" = {v}" : "";
    private static string DocInline(Element e) => string.IsNullOrWhiteSpace(e.Documentation) ? "" : $" // {e.Documentation.Split('\n')[0]}";

    private static void Doc(StringBuilder sb, int d, string text)
    {
        if (string.IsNullOrWhiteSpace(text)) return;
        Line(sb, d, $"doc /* {text.Replace("*/", "* /")} */");
    }

    private static void Line(StringBuilder sb, int depth, string s) => sb.Append(' ', depth * 4).AppendLine(s);

    /// <summary>Quotes a name if it isn't a plain identifier.</summary>
    public static string N(string name)
    {
        if (string.IsNullOrEmpty(name)) return "'unnamed'";
        var plain = (char.IsLetter(name[0]) || name[0] == '_') && name.All(c => char.IsLetterOrDigit(c) || c == '_') && !Keywords.Contains(name);
        return plain ? name : $"'{Q(name)}'";
    }

    private static string Q(string s) => s.Replace("\\", "\\\\").Replace("'", "\\'");

    private static readonly HashSet<string> Keywords = new()
    {
        "package", "part", "port", "attribute", "item", "def", "enum", "constraint", "requirement", "action", "state", "use", "case",
        "doc", "comment", "satisfy", "by", "verify", "allocate", "to", "dependency", "from", "first", "then", "transition", "if", "do",
        "in", "out", "inout", "include", "abstract", "ref", "import", "start", "done", "decide", "fork", "join", "merge", "objective", "subject",
        "verification", "interface", "connection", "connect", "flow", "accept", "send", "entry", "exit", "private", "public", "protected",
    };

    // ======================================================================= import

    public static (ModelRepository Model, ImportReport Report) Import(string text, string modelName = "Imported")
    {
        var p = new Parser(Tokenizer.Tokenize(text));
        var model = new ModelRepository(modelName);
        var ctx = new ImportContext(model);
        p.ParseBody(model.Root, ctx, topLevel: true);
        ctx.Resolve();
        // A single top-level package becomes the model itself.
        model.History.Clear();
        return (model, new ImportReport(ctx.Count, ctx.RelCount, ctx.Warnings));
    }

    private enum T { Ident, Name, Str, Sym, Comment, Number, Eof }

    private readonly record struct Tok(T Type, string Text, int Line);

    private static class Tokenizer
    {
        public static List<Tok> Tokenize(string s)
        {
            var list = new List<Tok>();
            var line = 1;
            var i = 0;
            while (i < s.Length)
            {
                var c = s[i];
                if (c == '\n') { line++; i++; continue; }
                if (char.IsWhiteSpace(c)) { i++; continue; }
                if (c == '/' && i + 1 < s.Length && s[i + 1] == '/')
                {
                    while (i < s.Length && s[i] != '\n') i++;
                    continue;
                }
                if (c == '/' && i + 1 < s.Length && s[i + 1] == '*')
                {
                    var end = s.IndexOf("*/", i + 2, StringComparison.Ordinal);
                    if (end < 0) end = s.Length - 2;
                    var body = s[(i + 2)..end];
                    list.Add(new Tok(T.Comment, CleanComment(body), line));
                    line += body.Count(ch => ch == '\n');
                    i = end + 2;
                    continue;
                }
                if (c == '\'')
                {
                    var sb = new StringBuilder();
                    i++;
                    while (i < s.Length && s[i] != '\'') { if (s[i] == '\\' && i + 1 < s.Length) i++; sb.Append(s[i]); i++; }
                    i++;
                    list.Add(new Tok(T.Name, sb.ToString(), line));
                    continue;
                }
                if (c == '"')
                {
                    var sb = new StringBuilder();
                    i++;
                    while (i < s.Length && s[i] != '"') { if (s[i] == '\\' && i + 1 < s.Length) i++; sb.Append(s[i]); i++; }
                    i++;
                    list.Add(new Tok(T.Str, sb.ToString(), line));
                    continue;
                }
                if (char.IsLetter(c) || c == '_')
                {
                    var st = i;
                    while (i < s.Length && (char.IsLetterOrDigit(s[i]) || s[i] == '_')) i++;
                    list.Add(new Tok(T.Ident, s[st..i], line));
                    continue;
                }
                if (char.IsDigit(c))
                {
                    var st = i;
                    while (i < s.Length && (char.IsDigit(s[i]) || s[i] == '.' && i + 1 < s.Length && char.IsDigit(s[i + 1]))) i++;
                    list.Add(new Tok(T.Number, s[st..i], line));
                    continue;
                }
                // multi-char symbols
                foreach (var sym in new[] { ":>>", ":>", "::", "..", "=>", ":=" })
                    if (string.CompareOrdinal(s, i, sym, 0, sym.Length) == 0) { list.Add(new Tok(T.Sym, sym, line)); i += sym.Length; goto next; }
                list.Add(new Tok(T.Sym, c.ToString(), line));
                i++;
                next:;
            }
            list.Add(new Tok(T.Eof, "", line));
            return list;
        }

        private static string CleanComment(string body) =>
            string.Join("\n", body.Split('\n').Select(l => l.Trim().TrimStart('*').Trim())).Trim();
    }

    private sealed class ImportContext(ModelRepository model)
    {
        public ModelRepository Model { get; } = model;
        public List<string> Warnings { get; } = new();
        public int Count;
        public int RelCount;
        public readonly List<(Element el, string type)> Types = new();
        public readonly List<(Element el, List<string> supers)> Supers = new();
        public readonly List<(ElementKind kind, Element owner, string src, string tgt, string? guard, string? effect, string? name, int line)> Rels = new();

        public Element Add(Element owner, ElementKind kind, string? name)
        {
            if (!Metamodel.CanOwn(owner.Kind, kind))
            {
                var fallback = Model.DefaultOwnerFor(owner, kind);
                if (!Metamodel.CanOwn(fallback.Kind, kind)) throw new FormatException($"{kind} cannot be placed in {owner.Kind}");
                owner = fallback;
            }
            var e = new Element(kind);
            ModelRepository.SetFieldForLoad(e, FieldKeys.Name, name);
            if (Metamodel.IsTypedFeature(kind)) ModelRepository.SetFieldForLoad(e, FieldKeys.Multiplicity, "1");
            Model.AttachForLoad(owner, e);
            Count++;
            return e;
        }

        private Element? Lookup(string qname, Element scope, Func<Element, bool>? filter = null)
        {
            var simple = qname.Contains("::") ? qname[(qname.LastIndexOf("::", StringComparison.Ordinal) + 2)..] : qname;
            filter ??= _ => true;
            // nearest scope first, then anywhere in the model
            for (var s = scope; s != null; s = s.Owner)
            {
                var hit = s.OwnedElements.FirstOrDefault(c => c.Name == simple && c is not Relationship && filter(c));
                if (hit != null) return hit;
            }
            return Model.AllElements.FirstOrDefault(c => c.Name == simple && c is not Relationship && filter(c));
        }

        public void Resolve()
        {
            foreach (var (el, type) in Types)
            {
                var simple = type.Contains("::") ? type[(type.LastIndexOf("::", StringComparison.Ordinal) + 2)..] : type;
                var t = Lookup(type, el.Owner!, c => Metamodel.IsClassifier(c.Kind));
                ModelRepository.SetFieldForLoad(el, FieldKeys.Type, t?.Id ?? simple);
            }
            foreach (var (el, supers) in Supers)
                foreach (var s in supers)
                {
                    var g = Lookup(s, el.Owner!, c => c.Kind == el.Kind);
                    if (g == null) { Warnings.Add($"Unresolved supertype '{s}' of '{el.Name}'"); continue; }
                    Model.AttachForLoad(Model.DefaultOwnerFor(el.Owner!, ElementKind.Generalization), new Relationship(ElementKind.Generalization, el, g));
                    RelCount++;
                }
            foreach (var (kind, owner, src, tgt, guard, effect, name, line) in Rels)
            {
                bool behavior = kind is ElementKind.Transition or ElementKind.ControlFlow or ElementKind.Message;
                var s = behavior ? FindNode(owner, src, initial: true) : Lookup(src, owner);
                var t = behavior ? FindNode(owner, tgt, initial: false) : Lookup(tgt, owner);
                if (s == null || t == null) { Warnings.Add($"Line {line}: unresolved {(s == null ? src : tgt)} in {kind}"); continue; }
                if (Metamodel.CheckEnds(kind, s.Kind, t.Kind) is { } problem) { Warnings.Add($"Line {line}: {problem}"); continue; }
                var r = new Relationship(kind, s, t);
                ModelRepository.SetFieldForLoad(r, FieldKeys.Guard, guard);
                if (kind == ElementKind.Message) ModelRepository.SetFieldForLoad(r, FieldKeys.MessageSort, effect);
                else ModelRepository.SetFieldForLoad(r, FieldKeys.Effect, effect);
                ModelRepository.SetFieldForLoad(r, FieldKeys.Name, name);
                var relOwner = behavior ? s.Owner! : Model.DefaultOwnerFor(owner, kind);
                Model.AttachForLoad(relOwner, r);
                RelCount++;
            }
        }

        private Element? FindNode(Element owner, string name, bool initial)
        {
            if (name == "start")
                return owner.OwnedElements.FirstOrDefault(c => c.Kind is ElementKind.InitialNode or ElementKind.InitialState)
                       ?? Add(owner, owner.Kind == ElementKind.Activity ? ElementKind.InitialNode : ElementKind.InitialState, null);
            if (name == "done")
                return owner.OwnedElements.FirstOrDefault(c => c.Kind is ElementKind.ActivityFinalNode or ElementKind.FinalState)
                       ?? Add(owner, owner.Kind == ElementKind.Activity ? ElementKind.ActivityFinalNode : ElementKind.FinalState, null);
            return owner.Descendants().FirstOrDefault(c => c.Name == name && c is not Relationship);
        }
    }

    private sealed class Parser(List<Tok> toks)
    {
        private int _i;
        private Tok Cur => toks[_i];
        private Tok Peek(int k = 1) => toks[Math.Min(_i + k, toks.Count - 1)];
        private bool Is(string text) => Cur.Type is T.Ident or T.Sym && Cur.Text == text;
        private Tok Next() => toks[_i++];
        private void SkipComments() { while (Cur.Type == T.Comment) _i++; }

        private bool Accept(string text)
        {
            if (!Is(text)) return false;
            _i++;
            return true;
        }

        private string ReadName()
        {
            SkipComments();
            if (Cur.Type is T.Ident or T.Name) return Next().Text;
            throw new FormatException($"Line {Cur.Line}: expected a name but found '{Cur.Text}'");
        }

        private string ReadQualified()
        {
            var sb = new StringBuilder(ReadName());
            while (Is("::") || Is(".")) { Next(); sb.Append("::").Append(ReadName()); }
            return sb.ToString();
        }

        public void ParseBody(Element owner, ImportContext ctx, bool topLevel = false)
        {
            while (true)
            {
                if (Cur.Type == T.Eof) { if (!topLevel) throw new FormatException("Unexpected end of file: missing '}'"); return; }
                if (Is("}")) { if (topLevel) throw new FormatException($"Line {Cur.Line}: unexpected '}}'"); Next(); return; }
                if (Cur.Type == T.Comment) { Next(); continue; }
                try { ParseMember(owner, ctx); }
                catch (FormatException ex) when (!ex.Message.Contains("end of file"))
                {
                    ctx.Warnings.Add(ex.Message);
                    SkipStatement();
                }
            }
        }

        private void SkipBlock()
        {
            var depth = 1;
            while (Cur.Type != T.Eof && depth > 0)
            {
                var t = Next();
                if (t.Type != T.Sym) continue;
                if (t.Text == "{") depth++;
                else if (t.Text == "}") depth--;
            }
        }

        /// <summary>Skips to the end of the current statement (a ';' or a balanced {...} block).</summary>
        private void SkipStatement()
        {
            var depth = 0;
            while (Cur.Type != T.Eof)
            {
                var t = Next();
                if (t.Type != T.Sym) continue;
                if (t.Text == "{") depth++;
                else if (t.Text == "}") { depth--; if (depth <= 0) return; }
                else if (t.Text == ";" && depth == 0) return;
            }
        }

        private void ParseMember(Element owner, ImportContext ctx)
        {
            // modifiers
            var isAbstract = false; string? direction = null; var isActor = false; string? messageSort = null;
            while (true)
            {
                if (Accept("abstract")) { isAbstract = true; continue; }
                if (Accept("public") || Accept("private") || Accept("protected") || Accept("ref") || Accept("variation")) continue;
                if (Is("in") || Is("out") || Is("inout")) { direction = Next().Text; continue; }
                if (Is("#")) { Next(); var tag = ReadName(); if (tag == "actor") isActor = true; else if (tag == "reply") messageSort = "reply"; else if (tag == "async") messageSort = "asynchCall"; else if (tag is "derivation" or "refinement" or "trace" or "extend") { ParseTaggedDependency(owner, ctx, tag); return; } continue; }
                break;
            }

            if (Accept("doc"))
            {
                if (Cur.Type is T.Ident or T.Name) Next(); // optional doc name
                var text = Cur.Type == T.Comment ? Next().Text : "";
                SetDoc(owner, text);
                Accept(";");
                return;
            }
            if (Accept("comment"))
            {
                if (Cur.Type is T.Ident or T.Name) Next(); // comment name
                if (Accept("about")) { ReadQualified(); while (Accept(",")) ReadQualified(); }
                var body = Cur.Type == T.Comment ? Next().Text : "";
                if (Metamodel.CanOwn(owner.Kind, ElementKind.Comment) && owner.Kind is ElementKind.Package or ElementKind.Model)
                    ModelRepository.SetFieldForLoad(ctx.Add(owner, ElementKind.Comment, null), FieldKeys.Body, body);
                Accept(";");
                return;
            }
            if (Accept("import")) { SkipStatement(); return; }
            if (Accept("package") || Accept("library"))
            {
                if (toks[_i - 1].Text == "library") Accept("package");
                var name = ReadName();
                Element pkg;
                if (owner.Kind == ElementKind.Model && owner.OwnedElements.Count == 0 && ctx.Count == 0 && owner.Name == "Imported")
                {
                    ModelRepository.SetFieldForLoad(owner, FieldKeys.Name, name);
                    pkg = owner;
                }
                else pkg = ctx.Add(owner, ElementKind.Package, name);
                if (Accept("{")) ParseBody(pkg, ctx); else Accept(";");
                return;
            }
            if (Accept("satisfy"))
            {
                Accept("requirement");
                var req = ReadQualified();
                Accept("by");
                var by = ReadQualified();
                ctx.Rels.Add((ElementKind.Satisfy, owner, by, req, null, null, null, Cur.Line));
                Accept(";");
                return;
            }
            if (Accept("allocate"))
            {
                var a = ReadQualified(); Accept("to"); var b = ReadQualified();
                ctx.Rels.Add((ElementKind.Allocate, owner, a, b, null, null, null, Cur.Line));
                Accept(";");
                return;
            }
            if (Accept("dependency")) { ParseDependency(owner, ctx, ElementKind.Dependency); return; }
            if (Accept("message"))
            {
                string? mname = null;
                if (Cur.Type is T.Ident or T.Name && !Is("from") && !Is("of")) mname = ReadName();
                if (Accept("of")) ReadQualified();
                Accept("from");
                var from = ReadQualified();
                Accept("to");
                var to = ReadQualified();
                ctx.Rels.Add((ElementKind.Message, owner, from, to, null, messageSort ?? "synchCall", mname, Cur.Line));
                Accept(";");
                return;
            }
            if (Accept("include"))
            {
                Accept("use"); Accept("case");
                var target = ReadQualified();
                ctx.Rels.Add((ElementKind.Include, owner, owner.Name, target, null, null, null, Cur.Line));
                Accept(";");
                return;
            }
            if (Accept("objective"))
            {
                Accept("{");
                while (!Is("}") && Cur.Type != T.Eof)
                {
                    if (Accept("verify")) { Accept("requirement"); var r = ReadQualified(); ctx.Rels.Add((ElementKind.Verify, owner, owner.Name, r, null, null, null, Cur.Line)); Accept(";"); }
                    else if (Cur.Type == T.Comment) Next();
                    else SkipStatement();
                }
                Accept("}");
                return;
            }
            if (Accept("verify"))
            {
                Accept("requirement");
                var r = ReadQualified();
                ctx.Rels.Add((ElementKind.Verify, owner, owner.Name, r, null, null, null, Cur.Line));
                Accept(";");
                return;
            }
            if (Is("transition")) { Next(); ParseSuccession(owner, ctx, ElementKind.Transition); return; }
            if (Is("first")) { ParseSuccession(owner, ctx, owner.Kind == ElementKind.StateMachine || owner.Kind == ElementKind.State ? ElementKind.Transition : ElementKind.ControlFlow); return; }
            if (Is("entry")) { Next(); if (Accept(";")) { } else SkipStatement(); return; }
            if (Is("then")) { SkipStatement(); return; }
            if (Is("decide") || Is("fork") || Is("join") || Is("merge"))
            {
                var kw = Next().Text;
                var name = Cur.Type is T.Ident or T.Name ? ReadName() : null;
                ctx.Add(owner, kw is "decide" or "merge" ? ElementKind.DecisionNode : ElementKind.ForkNode, name);
                Accept(";");
                return;
            }

            // definitions & usages
            var kind = ReadKindKeyword(out var isDef);
            if (kind == null)
            {
                // enum literal inside enum def ("Red;" or "enum Red;")
                if (owner.Kind == ElementKind.Enumeration && Cur.Type is T.Ident or T.Name)
                {
                    ctx.Add(owner, ElementKind.EnumerationLiteral, ReadName());
                    Accept(";");
                    return;
                }
                throw new FormatException($"Line {Cur.Line}: unsupported statement starting with '{Cur.Text}'");
            }
            if (isActor && kind == ElementKind.Block) kind = ElementKind.Actor;
            if (owner.Kind == ElementKind.Enumeration && kind == ElementKind.EnumerationLiteral)
            {
                ctx.Add(owner, ElementKind.EnumerationLiteral, ReadName());
                Accept(";");
                return;
            }

            string? reqId = null;
            if (Accept("<")) { reqId = ReadName(); Accept(">"); }
            var elName = Cur.Type is T.Ident or T.Name ? ReadName() : null;

            if (!isDef)
            {
                var usage = UsageKind(kind.Value, owner);
                if (usage == null) { SkipStatement(); return; }
                var e = ctx.Add(owner, usage.Value, elName);
                if (direction != null && usage == ElementKind.Port) ModelRepository.SetFieldForLoad(e, FieldKeys.Direction, direction);
                if (Accept(":")) ctx.Types.Add((e, ReadQualified()));
                else if (Accept(":>") || Accept(":>>")) { ReadQualified(); }
                if (Accept("["))
                {
                    var sb = new StringBuilder();
                    while (!Is("]") && Cur.Type != T.Eof) sb.Append(Next().Text);
                    Accept("]");
                    ModelRepository.SetFieldForLoad(e, FieldKeys.Multiplicity, sb.ToString());
                }
                if (Accept("=") || Accept(":="))
                {
                    var sb = new StringBuilder();
                    while (!Is(";") && !Is("{") && Cur.Type != T.Eof) sb.Append(Next().Text).Append(' ');
                    ModelRepository.SetFieldForLoad(e, FieldKeys.DefaultValue, sb.ToString().Trim());
                }
                if (Accept("{")) { if (Metamodel.IsNamespace(e.Kind)) ParseBody(e, ctx); else SkipBlock(); }
                else Accept(";");
                return;
            }

            var def = ctx.Add(owner, kind.Value, elName);
            if (isAbstract) ModelRepository.SetFieldForLoad(def, FieldKeys.IsAbstract, "true");
            if (reqId != null) ModelRepository.SetFieldForLoad(def, FieldKeys.RequirementId, reqId);
            if (Accept(":>") || Accept("specializes"))
            {
                var supers = new List<string> { ReadQualified() };
                while (Accept(",")) supers.Add(ReadQualified());
                ctx.Supers.Add((def, supers));
            }
            if (Accept("{"))
            {
                if (def.Kind == ElementKind.ConstraintBlock) ParseConstraintBody(def);
                else ParseBody(def, ctx);
            }
            else Accept(";");
        }

        private void ParseConstraintBody(Element def)
        {
            var sb = new StringBuilder();
            var depth = 1;
            while (Cur.Type != T.Eof)
            {
                var t = Next();
                if (t.Text == "{" && t.Type == T.Sym) depth++;
                if (t.Text == "}" && t.Type == T.Sym && --depth == 0) break;
                if (t.Type == T.Comment) { ModelRepository.SetFieldForLoad(def, FieldKeys.Documentation, t.Text); continue; }
                if (t.Text == "doc") continue;
                sb.Append(t.Text).Append(' ');
            }
            ModelRepository.SetFieldForLoad(def, FieldKeys.Body, sb.ToString().Trim());
        }

        private void ParseDependency(Element owner, ImportContext ctx, ElementKind kind)
        {
            if (Cur.Type is T.Ident or T.Name && !Is("from")) ReadName();
            Accept("from");
            var a = ReadQualified(); Accept("to"); var b = ReadQualified();
            ctx.Rels.Add((kind, owner, a, b, null, null, null, Cur.Line));
            Accept(";");
        }

        private void ParseTaggedDependency(Element owner, ImportContext ctx, string tag)
        {
            Accept("dependency");
            ParseDependency(owner, ctx, tag switch { "derivation" => ElementKind.DeriveReqt, "refinement" => ElementKind.Refine, "extend" => ElementKind.Extend, _ => ElementKind.Trace });
        }

        private void ParseSuccession(Element owner, ImportContext ctx, ElementKind kind)
        {
            string? name = null;
            if (Cur.Type is T.Ident or T.Name && !Is("first")) name = ReadName();
            Accept("first");
            var from = ReadQualified();
            string? guard = null, effect = null;
            if (Accept("accept")) ReadQualified();
            if (Accept("if")) guard = ReadUntil("do", "then", ";");
            if (Accept("do")) effect = ReadUntil("then", ";");
            Accept("then");
            var to = ReadQualified();
            ctx.Rels.Add((kind, owner, from, to, guard, effect, name, Cur.Line));
            Accept(";");
        }

        private string ReadUntil(params string[] stops)
        {
            var sb = new StringBuilder();
            while (Cur.Type != T.Eof && !stops.Any(Is)) sb.Append(Next().Text).Append(' ');
            return sb.ToString().Trim();
        }

        private ElementKind? ReadKindKeyword(out bool isDef)
        {
            isDef = false;
            ElementKind? k = null;
            if (Accept("part")) k = ElementKind.Block;
            else if (Accept("port")) k = ElementKind.InterfaceBlock;
            else if (Accept("attribute")) k = ElementKind.ValueType;
            else if (Accept("item")) k = ElementKind.Block;
            else if (Accept("enum")) k = Is("def") ? ElementKind.Enumeration : ElementKind.EnumerationLiteral;
            else if (Accept("constraint")) k = ElementKind.ConstraintBlock;
            else if (Accept("requirement")) k = ElementKind.Requirement;
            else if (Accept("verification")) k = ElementKind.TestCase;
            else if (Accept("action")) k = ElementKind.Activity;
            else if (Accept("state")) k = ElementKind.StateMachine;
            else if (Accept("interface")) k = ElementKind.InterfaceBlock;
            else if (Accept("use")) { Accept("case"); k = ElementKind.UseCase; }
            else if (Accept("occurrence")) k = Is("def") ? ElementKind.Interaction : ElementKind.Block;
            if (k != null && Accept("def")) isDef = true;
            return k;
        }

        /// <summary>Maps a usage keyword to a model element given its owner.</summary>
        private static ElementKind? UsageKind(ElementKind defKind, Element owner) => defKind switch
        {
            ElementKind.Block when owner.Kind == ElementKind.Interaction => ElementKind.Lifeline,
            ElementKind.Block or ElementKind.ValueType => Metamodel.CanOwn(owner.Kind, ElementKind.Property) ? ElementKind.Property : null,
            ElementKind.InterfaceBlock => Metamodel.CanOwn(owner.Kind, ElementKind.Port) ? ElementKind.Port : null,
            ElementKind.Activity => owner.Kind == ElementKind.Activity ? ElementKind.Action : null,
            ElementKind.StateMachine => owner.Kind is ElementKind.StateMachine or ElementKind.State ? ElementKind.State : null,
            ElementKind.Requirement => owner.Kind == ElementKind.Requirement ? ElementKind.Requirement : null,
            _ => null,
        };

        private static void SetDoc(Element owner, string text)
        {
            if (owner.Kind == ElementKind.Requirement) ModelRepository.SetFieldForLoad(owner, FieldKeys.Text, text);
            else ModelRepository.SetFieldForLoad(owner, FieldKeys.Documentation, text);
        }
    }
